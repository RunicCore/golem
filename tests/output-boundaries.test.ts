import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test, type TestContext } from 'node:test';
import type { GolemConfig, GolemJob } from '#golem/config';
import { codecKeysPath } from '#golem/generated-paths';
import { applyJob, loadInventory, removeRetiredJobs } from '#golem/outputs';

function modelContent(value: number): string {
  return `/* Generated by @exprtlabs/golem-model. Do not edit. */\nexport const value = ${value};\n`;
}

function openApiContent(value: number): string {
  return `/* Generated by @exprtlabs/golem-openapi. Do not edit. */\nexport const value = ${value};\n`;
}

function configFor(directory: string, job: GolemJob): GolemConfig {
  return {
    directory,
    configFile: path.join(directory, 'golem.yaml'),
    inventoryFile: path.join(directory, '.golem/outputs.json'),
    tsconfig: path.join(directory, 'tsconfig.json'),
    tsconfigNamed: false,
    profile: { mobx: false, validation: true },
    jobs: [job],
  };
}

function openApiJob(output: string): GolemJob {
  return {
    id: `openapi:${path.basename(output)}`,
    kind: 'openapi',
    package: '@exprtlabs/golem-openapi',
    options: {
      input: path.join(path.dirname(output), 'api.json'),
      output,
      profile: { mobx: false, validation: true },
    },
  };
}

function modelJob(root: string, output: string, sources?: readonly string[]): GolemJob {
  return {
    id: 'models:.',
    kind: 'models',
    package: '@exprtlabs/golem-model',
    options: {
      root,
      output,
      profile: { mobx: false, validation: true },
      ...(sources === undefined ? {} : { sources }),
    },
  };
}

function fixture(t: TestContext): string {
  const directory = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'golem-output-boundaries-')));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  return directory;
}

test('a configured symlink output is canonicalized before inventory recording', (t: TestContext) => {
  const directory = fixture(t);
  const target = path.join(directory, 'external-sdk');
  const output = path.join(directory, 'sdk-link');
  fs.mkdirSync(target, { recursive: true });
  fs.symlinkSync(target, output, 'dir');
  const job = openApiJob(output);
  const config = configFor(directory, job);
  const filename = path.join(output, 'client.ts');

  applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]);

  const inventory = loadInventory(config);
  const key = path.relative(directory, path.join(target, 'client.ts')).replaceAll(path.sep, '/');
  assert.equal(inventory.files[key]?.destination, path.relative(directory, target).replaceAll(path.sep, '/'));
  assert.equal(fs.readFileSync(path.join(target, 'client.ts'), 'utf8'), openApiContent(1));
});

test('a symlinked inventory parent is rejected before check or generation writes', (t: TestContext) => {
  const directory = fixture(t);
  const outside = path.join(directory, 'outside-inventory');
  fs.mkdirSync(outside, { recursive: true });
  fs.symlinkSync(outside, path.join(directory, '.golem'), 'dir');
  const output = path.join(directory, 'sdk');
  fs.mkdirSync(output, { recursive: true });
  const job = openApiJob(output);
  const config = configFor(directory, job);
  const filename = path.join(output, 'client.ts');
  const inventory = { version: 1 as const, files: {} };
  const expected = [{ path: filename, content: openApiContent(1) }];

  assert.throws(() => loadInventory(config), /inventory.*symbolic link/i);
  assert.throws(() => applyJob(config, inventory, job, expected, true), /inventory.*symbolic link/i);
  assert.throws(() => applyJob(config, inventory, job, expected, false), /inventory.*symbolic link/i);
  assert.equal(fs.existsSync(filename), false);
  assert.equal(fs.existsSync(path.join(outside, 'outputs.json')), false);
});

