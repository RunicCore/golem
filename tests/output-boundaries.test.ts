import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test, type TestContext } from 'node:test';
import type { GolemConfig, GolemJob } from '#golem/config';
import { applyJob, loadInventory, removeRetiredJobs } from '#golem/outputs';
import { configFor, jobWithFacts } from './support/output-config.js';

function modelContent(value: number): string {
  return `/* Generated by @exprtlabs/golem-model. Do not edit. */\nexport const value = ${value};\n`;
}

function openApiContent(value: number): string {
  return `/* Generated by @exprtlabs/golem-openapi. Do not edit. */\nexport const value = ${value};\n`;
}

function openApiJob(output: string): GolemJob {
  return jobWithFacts(`openapi:${path.basename(output)}`, '@exprtlabs/golem-openapi', { outputs: [{ path: output, kind: 'folder' }] });
}

/** The OpenAPI `job` that writes `output` (by default the job of `openApiJob`), the config of `directory` that has it, and the `client.ts` it writes. */
function openApiProject(directory: string, output: string, job: GolemJob = openApiJob(output)): { job: GolemJob; config: GolemConfig; filename: string } {
  return { job, config: configFor(directory, job), filename: path.join(output, 'client.ts') };
}

function modelJob(root: string, output: string, sources?: readonly string[]): GolemJob {
  // The output and the folders of the sources come first, the root last: the narrower destination is the one a file records.
  return jobWithFacts('models:.', '@exprtlabs/golem-model', { ownedRoots: [output, ...(sources === undefined ? [path.join(root, 'src')] : sources.map(source => path.dirname(source))), root] });
}

function fixture(t: TestContext): string {
  const directory = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'golem-output-boundaries-')));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  return directory;
}

test('a configured symlink output is canonicalized before inventory recording', (t: TestContext) => {
  const directory = fixture(t);
  const target = path.join(directory, 'external-sdk');
  const output = path.join(directory, 'sdk-link');
  fs.mkdirSync(target, { recursive: true });
  fs.symlinkSync(target, output, 'dir');
  const { job, config, filename } = openApiProject(directory, output);

  applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]);

  const inventory = loadInventory(config);
  const key = path.relative(directory, path.join(target, 'client.ts')).replaceAll(path.sep, '/');
  assert.equal(inventory.files[key]?.destination, path.relative(directory, target).replaceAll(path.sep, '/'));
  assert.equal(fs.readFileSync(path.join(target, 'client.ts'), 'utf8'), openApiContent(1));
});

test('a symlinked inventory parent is rejected before check or generation writes', (t: TestContext) => {
  const directory = fixture(t);
  const outside = path.join(directory, 'outside-inventory');
  fs.mkdirSync(outside, { recursive: true });
  fs.symlinkSync(outside, path.join(directory, '.golem'), 'dir');
  const output = path.join(directory, 'sdk');
  fs.mkdirSync(output, { recursive: true });
  const { job, config, filename } = openApiProject(directory, output);
  const inventory = { version: 1 as const, files: {} };
  const expected = [{ path: filename, content: openApiContent(1) }];

  assert.throws(() => loadInventory(config), /inventory.*symbolic link/i);
  assert.throws(() => applyJob(config, inventory, job, expected, true), /inventory.*symbolic link/i);
  assert.throws(() => applyJob(config, inventory, job, expected, false), /inventory.*symbolic link/i);
  assert.equal(fs.existsSync(filename), false);
  assert.equal(fs.existsSync(path.join(outside, 'outputs.json')), false);
});

test('a parent symlink escape is rejected before an expected output write', (t: TestContext) => {
  const directory = fixture(t);
  const output = path.join(directory, 'sdk');
  const outside = path.join(directory, 'outside');
  fs.mkdirSync(output, { recursive: true });
  fs.mkdirSync(outside, { recursive: true });
  fs.symlinkSync(outside, path.join(output, 'escape'), 'dir');
  const { job, config } = openApiProject(directory, output);
  const filename = path.join(output, 'escape/client.ts');

  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]),
    /escapes.*symbolic link|symbolic link.*escapes/i,
  );
  assert.equal(fs.existsSync(path.join(outside, 'client.ts')), false);
  assert.equal(fs.existsSync(config.inventoryFile), false);
});

test('replacing the configured output root with a symlink is rejected before reconciliation', (t: TestContext) => {
  const directory = fixture(t);
  const output = path.join(directory, 'sdk');
  const outside = path.join(directory, 'outside');
  fs.mkdirSync(output, { recursive: true });
  fs.mkdirSync(outside, { recursive: true });
  const { job, config, filename } = openApiProject(directory, output);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]);

  fs.rmSync(output, { recursive: true, force: true });
  fs.symlinkSync(outside, output, 'dir');
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(2) }]),
    /destination through symbolic link|symbolic link/i,
  );
  assert.equal(fs.existsSync(path.join(outside, 'client.ts')), false);
});

test('replacing an ancestor of the recorded destination with a symlink is rejected', (t: TestContext) => {
  const directory = fixture(t);
  const generated = path.join(directory, 'generated');
  const output = path.join(generated, 'sdk');
  const outside = path.join(directory, 'outside');
  fs.mkdirSync(output, { recursive: true });
  fs.mkdirSync(path.join(outside, 'sdk'), { recursive: true });
  const { job, config, filename } = openApiProject(directory, output);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]);

  fs.rmSync(generated, { recursive: true, force: true });
  fs.symlinkSync(outside, generated, 'dir');
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(2) }]),
    /moved through a symbolic link|symbolic link/i,
  );
  assert.equal(fs.existsSync(path.join(outside, 'sdk', 'client.ts')), false);
});

test('a final symlink is never adopted as an expected generated output', (t: TestContext) => {
  const directory = fixture(t);
  const output = path.join(directory, 'sdk');
  const outside = path.join(directory, 'handwritten.ts');
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(outside, 'handwritten\n');
  const filename = path.join(output, 'client.ts');
  fs.symlinkSync(outside, filename);
  const job = openApiJob(output);
  const config = configFor(directory, job);

  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]),
    /non-regular|symbolic link/i,
  );
  assert.equal(fs.readFileSync(outside, 'utf8'), 'handwritten\n');
});

test('model output changes retire old shared artifacts through recorded destinations', (t: TestContext) => {
  const directory = fixture(t);
  const oldOutput = path.join(directory, '..', `golem-old-model-output-${path.basename(directory)}`);
  const newOutput = path.join(directory, '..', `golem-new-model-output-${path.basename(directory)}`);
  fs.mkdirSync(oldOutput, { recursive: true });
  fs.mkdirSync(newOutput, { recursive: true });
  t.after(() => {
    fs.rmSync(oldOutput, { recursive: true, force: true });
    fs.rmSync(newOutput, { recursive: true, force: true });
  });
  const oldJob = modelJob(directory, oldOutput);
  const oldConfig = configFor(directory, oldJob);
  const oldFile = path.join(oldOutput, 'models.generated.ts');
  applyJob(oldConfig, loadInventory(oldConfig), oldJob, [{ path: oldFile, content: modelContent(1) }]);

  const nextJob = modelJob(directory, newOutput);
  const nextConfig = configFor(directory, nextJob);
  const newFile = path.join(newOutput, 'models.generated.ts');
  applyJob(nextConfig, loadInventory(nextConfig), nextJob, [{ path: newFile, content: modelContent(2) }]);

  assert.equal(fs.existsSync(oldFile), false);
  assert.equal(fs.readFileSync(newFile, 'utf8'), modelContent(2));
  const inventory = loadInventory(nextConfig);
  const key = path.relative(directory, newFile).replaceAll(path.sep, '/');
  assert.equal(inventory.files[key].destination, path.relative(directory, newOutput).replaceAll(path.sep, '/'));
});

test('a model inside models.root but outside src writes its generated file', (t: TestContext) => {
  const directory = fixture(t);
  const model = path.join(directory, 'lib/money.model.ts');
  fs.mkdirSync(path.dirname(model), { recursive: true });
  fs.writeFileSync(model, 'export type TMoney = unknown;\n');
  const job = modelJob(directory, path.join(directory, 'generated'));
  const config = configFor(directory, job);
  const filename = path.join(directory, 'lib/money.model.generated.ts');

  applyJob(config, loadInventory(config), job, [{ path: filename, content: modelContent(1) }]);

  assert.equal(fs.readFileSync(filename, 'utf8'), modelContent(1));
  assert.equal(loadInventory(config).files['lib/money.model.generated.ts']?.destination, '.');
});

test('an inventory entry without its destination or destination kind is invalid', (t: TestContext) => {
  const directory = fixture(t);
  const output = path.join(directory, 'generated');
  const job = modelJob(directory, output);
  const config = configFor(directory, job);
  const filename = path.join(output, 'models.generated.ts');
  applyJob(config, loadInventory(config), job, [{ path: filename, content: modelContent(1) }]);
  const key = path.relative(directory, filename).replaceAll(path.sep, '/');
  for (const field of ['destination', 'destinationKind']) {
    const inventory = JSON.parse(fs.readFileSync(config.inventoryFile, 'utf8')) as {
      files: Record<string, Record<string, unknown>>;
    };
    const recorded = inventory.files[key];
    delete recorded[field];
    fs.writeFileSync(config.inventoryFile, `${JSON.stringify(inventory, null, 2)}\n`);
    assert.throws(() => loadInventory(config), /Invalid generated inventory/, field);
    applyJob(config, { version: 1, files: {} }, job, [{ path: filename, content: modelContent(1) }]);
  }
  assert.equal(fs.existsSync(filename), true);
});

test('a retired OpenAPI output is removed only through its recorded, unmoved destination', (t: TestContext) => {
  const directory = fixture(t);
  const generated = path.join(directory, 'generated');
  const output = path.join(generated, 'sdk');
  fs.mkdirSync(output, { recursive: true });
  const { job, config, filename } = openApiProject(directory, output, jobWithFacts('openapi:generated/sdk', '@exprtlabs/golem-openapi', { outputs: [{ path: output, kind: 'folder' }] }));
  applyJob(config, loadInventory(config), job, [{ path: filename, content: openApiContent(1) }]);

  const retiredConfig: GolemConfig = { ...config, jobs: [] };
  assert.throws(() => removeRetiredJobs(retiredConfig, loadInventory(config), true), /removed jobs/);

  const outside = path.join(directory, 'outside');
  fs.mkdirSync(path.join(outside, 'sdk'), { recursive: true });
  fs.rmSync(generated, { recursive: true, force: true });
  fs.symlinkSync(outside, generated, 'dir');
  assert.throws(
    () => removeRetiredJobs(retiredConfig, loadInventory(config), false),
    /destination through symbolic link|symbolic link/i,
  );
  assert.equal(fs.existsSync(path.join(outside, 'sdk', 'client.ts')), false);
});
