test('checkFormat accepts valid values, rejects invalid ones, and ignores other types', () => {
  const failures = formatRows.filter(([format, value, valid]) => checkFormat(format, value) !== valid)
    .map(([format, value, valid]) => `${format} ${JSON.stringify(value)} should be ${valid ? 'valid' : 'invalid'}`);
  assert.deepEqual(failures, []);
});

test('isKnownFormat names the OpenAPI formats that check no value', () => {
  for (const format of ['media-range', 'password', 'binary']) assert.equal(isKnownFormat(format), true, format);
  assert.equal(isKnownFormat('unknown-format'), false);
});

