test('jsonEqual follows JSON Schema equality', () => {
  const failures = equalRows.filter(([left, right, equal]) => jsonEqual(left, right) !== equal)
    .map(([left, right, equal]) => `${JSON.stringify(left)} and ${JSON.stringify(right)} should be ${equal ? 'equal' : 'different'}`);
  assert.deepEqual(failures, []);
});

test('codePointLength counts code points, not UTF-16 units', () => {
  assert.equal(codePointLength('a\u{1F600}'), 2);
  assert.equal(codePointLength(''), 0);
  assert.equal(codePointLength('\u{1F600}\u{1F600}'), 2);
  assert.equal(codePointLength('\ud83d'), 1);
  assert.equal(codePointLength('\ud83dx'), 2);
});

