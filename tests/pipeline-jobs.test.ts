import { createFixtureProject, linkProjectPackages, snapshotFilesystem } from './fixture-project.js';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { test, type TestContext } from 'node:test';
import { runPipeline } from '#golem/cli';
import { workspace } from './support/process.js';
import { generate as generateModels } from '@exprtlabs/golem-model/generator';

test('model generation rejects an SDK manifest whose profile differs from the configured global profile', (t: TestContext) => {
  const root = createFixtureProject(t, 'golem-pipeline-profile-');

  fs.mkdirSync(path.join(root, 'src'), { recursive: true });
  fs.writeFileSync(path.join(root, 'tsconfig.json'), JSON.stringify({
    compilerOptions: {
      strict: true,
      target: 'ES2022',
      module: 'ESNext',
      moduleResolution: 'Bundler',
      skipLibCheck: true,
    },
    include: ['src/**/*.ts'],
  }));
  const source = path.join(root, 'src/cart.model.ts');
  fs.writeFileSync(source, [
    'type IModel<Fields extends object, Options = {}> = { fields: Fields; options: Options };',
    'export type TCart = IModel<{ note: string }>;',
    '',
  ].join('\n'));
  const manifest = path.join(root, 'sdk/model-manifest.json');
  fs.mkdirSync(path.dirname(manifest), { recursive: true });
  fs.writeFileSync(manifest, JSON.stringify({
    profile: { mobx: true, validation: true, allowAny: false },
    models: [],
  }));

  assert.throws(
    () => generateModels({
      root,
      sources: [source],
      profile: { mobx: false, validation: false },
      manifestInputs: [manifest],
    }),
    /profile mismatch/,
  );
  assert.equal(fs.existsSync(path.join(root, 'src/cart.model.generated.ts')), false);
});

/** A package whose block `chain` lists jobs; each declares the files and folder it reads and the file it writes, so a test lays out any read edge. */
const CHAIN_PLAN = `import path from 'node:path';
export const plan = {
  declare({ directory, block }) {
    const at = (name) => path.resolve(directory, name);
    return block.jobs.map((job) => ({
      facts: {
        id: job.id, outputs: [{ path: at(job.writes), kind: 'file' }], ownedRoots: [],
        inputFiles: job.readsFile ? [at(job.readsFile)] : [], inputFolders: job.readsFolder ? [at(job.readsFolder)] : [],
        readsProgram: false, provides: [], needs: [], hooks: [], watch: [],
      },
      options: { output: at(job.writes), consumes: job.consumes ? at(job.consumes) : undefined, diagnose: job.diagnose, failWhenExists: at('fail-' + job.id), missing: at('missing.json') },
    }));
  },
};
`;
/** The generator of the package: it announces and writes the text of the file it consumes, fails when its fail file exists, and reports an error diagnostic with a manifest that has no artifact when asked. */
const CHAIN_GENERATOR = `import fs from 'node:fs';
export const apiVersion = 1;
export function generate(context) {
  if (fs.existsSync(context.failWhenExists)) throw new Error('chain job failed');
  if (context.diagnose) return { artifacts: [], manifestPaths: [context.missing], watchInputs: [], diagnostics: [{ severity: 'error', code: context.diagnose, message: 'reported' }] };
  if (context.consumes) context.onInput(context.consumes);
  const text = context.consumes ? fs.readFileSync(context.consumes, 'utf8') : 'none';
  return { artifacts: [{ path: context.output, content: '/* Generated by @fixture/chain. Do not edit. */\\n' + text + '\\n' }], manifestPaths: [], watchInputs: [] };
}
`;

/** A project whose package `@fixture/chain` registers the block `chain`, with `jobs` as the lines of its job list. */
function chainProject(t: TestContext, jobs: readonly string[]): { root: string; config: string } {
  const root = createFixtureProject(t, 'golem-pipeline-chain-');
  linkProjectPackages(root, { '@exprtlabs/golem': path.join(workspace, 'packages/golem') });
  fs.writeFileSync(path.join(root, 'package.json'), '{"name":"golem-chain-fixture","type":"module","dependencies":{"@fixture/chain":"*"}}');
  const chain = path.join(root, 'node_modules/@fixture/chain');
  fs.mkdirSync(chain, { recursive: true });
  fs.writeFileSync(path.join(chain, 'package.json'), JSON.stringify({ name: '@fixture/chain', version: '1.0.0', type: 'module', exports: { './plan': './plan.js', './generator': './generator.js' }, golem: { apiVersion: 2, block: 'chain', plan: './plan', generator: './generator' } }));
  fs.writeFileSync(path.join(chain, 'plan.js'), CHAIN_PLAN);
  fs.writeFileSync(path.join(chain, 'generator.js'), CHAIN_GENERATOR);
  fs.writeFileSync(path.join(root, 'source.txt'), 'one');
  fs.writeFileSync(path.join(root, 'other.txt'), 'two');
  const config = path.join(root, 'golem.yaml');
  fs.writeFileSync(config, ['version: 1', 'chain:', '  jobs:', ...jobs.map(job => `    - ${job}`), ''].join('\n'));
  return { root, config };
}

const FIRST = '{ id: first, readsFile: source.txt, consumes: source.txt, writes: out/first.txt }';
const SECOND = '{ id: second, readsFolder: out, consumes: out/first.txt, writes: next/second.txt }';

test('a changed file reruns the jobs that read it, and the jobs that read a folder holding its output, and no other', async (t: TestContext) => {
  // protects: T-766 inputs and the consumer edge come from job facts, not from job kinds
  const { root, config } = chainProject(t, [FIRST, SECOND, '{ id: unrelated, readsFile: other.txt, consumes: other.txt, writes: next/unrelated.txt }']);
  const state = await runPipeline(config);
  assert.deepEqual([...state.ran].sort(), ['first', 'second', 'unrelated']);

  const source = path.join(root, 'source.txt');
  fs.writeFileSync(source, 'changed');
  const rerun = await runPipeline(config, { previous: state, changedInputs: [source] });
  assert.deepEqual([...rerun.ran].sort(), ['first', 'second']);
  assert.match(fs.readFileSync(path.join(root, 'next/second.txt'), 'utf8'), /\nchanged\n/);
});

test('a job that reports an error diagnostic shows it, not an error about its manifest', async (t: TestContext) => {
  // protects: T-735 golem generate prints a generator's error diagnostics before it checks the result for a manifest
  const { config } = chainProject(t, ['{ id: first, writes: out/first.txt, diagnose: CHAIN_REPORTED }']);

  await assert.rejects(() => runPipeline(config), /CHAIN_REPORTED/);
});

test('a downstream job failure preserves the completed job and a later run repairs inventory', async (t: TestContext) => {
  const { root, config } = chainProject(t, [FIRST, SECOND]);
  fs.writeFileSync(path.join(root, 'fail-second'), '');

  await assert.rejects(() => runPipeline(config), /Generator @fixture\/chain failed for second: chain job failed/);
  assert.equal(fs.existsSync(path.join(root, 'out/first.txt')), true);
  assert.equal(fs.existsSync(path.join(root, 'next/second.txt')), false);
  const interrupted = JSON.parse(fs.readFileSync(path.join(root, '.golem/outputs.json'), 'utf8')) as { files: Record<string, unknown> };
  assert.deepEqual(Object.keys(interrupted.files), ['out/first.txt']);

  fs.rmSync(path.join(root, 'fail-second'));
  await runPipeline(config);
  assert.equal(fs.existsSync(path.join(root, 'next/second.txt')), true);
  await runPipeline(config, { check: true });
});

test('retiring a job removes its unmodified outputs before its consumer runs', async (t: TestContext) => {
  const { root, config } = chainProject(t, [FIRST, SECOND]);
  await runPipeline(config);
  assert.equal(fs.existsSync(path.join(root, 'out/first.txt')), true);

  fs.writeFileSync(config, ['version: 1', 'chain:', '  jobs:', `    - ${SECOND}`, ''].join('\n'));
  await assert.rejects(() => runPipeline(config), /Generator @fixture\/chain failed for second: ENOENT/);
  assert.equal(fs.existsSync(path.join(root, 'out/first.txt')), false);
  const inventory = JSON.parse(fs.readFileSync(path.join(root, '.golem/outputs.json'), 'utf8')) as { files: Record<string, unknown> };
  assert.equal(Object.keys(inventory.files).some(filename => filename.startsWith('out/')), false);
});

test('check reports stale outputs without changing generated files or inventory', async (t: TestContext) => {
  const { root, config } = chainProject(t, [FIRST, SECOND]);
  await runPipeline(config);
  fs.writeFileSync(path.join(root, 'source.txt'), 'changed');
  const before = snapshotFilesystem(root);

  await assert.rejects(() => runPipeline(config, { check: true }), /stale/);
  assert.deepEqual(snapshotFilesystem(root), before);
});
