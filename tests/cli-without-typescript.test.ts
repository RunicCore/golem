import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test, { before, after } from 'node:test';
import { command, workspace } from './support/process.js';

// A project that does not have TypeScript: golem is copied out of the workspace so that no ancestor
// node_modules offers a TypeScript either, and only the commands that need a compiler may ask for one.
let installRoot: string;
let binary: string;

before(() => {
  installRoot = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'golem-no-typescript-')));
  const installed = path.join(installRoot, 'node_modules/@exprtlabs/golem');
  fs.mkdirSync(path.dirname(installed), { recursive: true });
  fs.cpSync(path.join(workspace, 'packages/golem/dist'), path.join(installed, 'dist'), { recursive: true });
  fs.copyFileSync(path.join(workspace, 'packages/golem/package.json'), path.join(installed, 'package.json'));
  fs.symlinkSync(path.join(workspace, 'node_modules/yaml'), path.join(installRoot, 'node_modules/yaml'));
  binary = path.join(installed, 'dist/bin/golem.js');
  // A third-party generator is a job that is neither models nor controllers: no job of golem's own, so no compiler is borrowed.
  const provider = path.join(installRoot, 'node_modules/@fixture/gen');
  fs.mkdirSync(provider, { recursive: true });
  fs.writeFileSync(path.join(provider, 'package.json'), JSON.stringify({ name: '@fixture/gen', version: '1.0.0-rc', type: 'module', exports: { './generator': './index.js' } }));
  fs.writeFileSync(path.join(provider, 'index.js'), `import path from 'node:path';
export const apiVersion = 1;
export function generate(context) {
  return { apiVersion: 1, artifacts: [{ path: path.join(context.output, 'note.ts'), content: '/* Generated by @fixture/gen. Do not edit. */\\nexport const note = 1;\\n' }], manifestPaths: [], watchInputs: [] };
}
`);
});

// A user's own GOLEM_TYPESCRIPT_ROOT (the TypeScript 6 lane sets one) would replace the root golem chooses.
const CHOSEN_ROOT = { GOLEM_TYPESCRIPT_ROOT: undefined };
const GENERATOR_ONLY = ['version: 1', 'generators:', "  - package: '@fixture/gen'", '    output: gen', ''].join('\n');
after(() => fs.rmSync(installRoot, { recursive: true, force: true }));

function project(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(installRoot, 'project-'));
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(root, name), text);
  return root;
}

test('golem --help does not need TypeScript', async () => {
  const root = project({});
  const help = await command(root, process.execPath, [binary, '--help']);
  assert.match(help.stdout, /Usage: golem /);
});

test('a configured provider that is not installed is reported without TypeScript', async () => {
  const root = project({ 'golem.yaml': 'version: 1\nopenapi:\n  - input: api.json\n    output: sdk\n    name: Api\n', 'api.json': '{}', 'tsconfig.json': '{}' });
  const result = await command(root, process.execPath, [binary, 'generate'], { allowFailure: true, env: CHOSEN_ROOT });
  assert.notEqual(result.code, 0);
  assert.match(result.stderr, /openapi is configured.*not installed/);
});

test('a config with no models or controllers job generates without TypeScript', async () => {
  const root = project({ 'golem.yaml': GENERATOR_ONLY, 'tsconfig.json': '{}' });
  await command(root, process.execPath, [binary, 'generate'], { env: CHOSEN_ROOT });
  await command(root, process.execPath, [binary, 'check'], { env: CHOSEN_ROOT });
  assert.equal(fs.readFileSync(path.join(root, 'gen/note.ts'), 'utf8'), '/* Generated by @fixture/gen. Do not edit. */\nexport const note = 1;\n');
});

test('an installed TypeScript that golem does not support is still an error', async () => {
  const unsupported = project({});
  fs.mkdirSync(path.join(unsupported, 'node_modules/typescript'), { recursive: true });
  fs.writeFileSync(path.join(unsupported, 'node_modules/typescript/package.json'), JSON.stringify({ name: 'typescript', version: '5.9.0' }));
  const root = project({ 'golem.yaml': GENERATOR_ONLY, 'tsconfig.json': '{}' });
  await command(root, process.execPath, [binary, 'generate'], { env: CHOSEN_ROOT });
  const result = await command(root, process.execPath, [binary, 'check'], { allowFailure: true, env: { GOLEM_TYPESCRIPT_ROOT: unsupported } });
  assert.notEqual(result.code, 0);
  assert.match(result.stderr, /golem supports TypeScript 6\.0\+ and 7\.1\+; found 5\.9\.0/);
});

test('the TypeScript of the directory of golem.yaml is the one used, wherever the command runs from, unless the user names another', async () => {
  const configured = project({ 'golem.yaml': GENERATOR_ONLY, 'tsconfig.json': '{}' });
  fs.mkdirSync(path.join(configured, 'node_modules/typescript'), { recursive: true });
  fs.writeFileSync(path.join(configured, 'node_modules/typescript/package.json'), JSON.stringify({ name: 'typescript', version: '5.9.0' }));
  const elsewhere = project({});
  const config = path.join(configured, 'golem.yaml');
  await command(elsewhere, process.execPath, [binary, 'generate', '--config', config], { env: CHOSEN_ROOT });
  const result = await command(elsewhere, process.execPath, [binary, 'check', '--config', config], { allowFailure: true, env: CHOSEN_ROOT });
  assert.notEqual(result.code, 0);
  assert.match(result.stderr, /golem supports TypeScript 6\.0\+ and 7\.1\+; found 5\.9\.0/);
  // GOLEM_TYPESCRIPT_ROOT set by the user wins: this directory has no TypeScript, so the scan is skipped.
  await command(elsewhere, process.execPath, [binary, 'check', '--config', config], { env: { GOLEM_TYPESCRIPT_ROOT: elsewhere } });
});

test('the TypeScript of the directory of the tsconfig golem.yaml names is the one used, not the yaml directory', async () => {
  const root = project({ 'golem.yaml': 'version: 1\ntsconfig: app/tsconfig.json\nmodels:\n  root: app\n' });
  fs.mkdirSync(path.join(root, 'app/node_modules/typescript'), { recursive: true });
  fs.writeFileSync(path.join(root, 'app/tsconfig.json'), '{}');
  fs.writeFileSync(path.join(root, 'app/node_modules/typescript/package.json'), JSON.stringify({ name: 'typescript', version: '5.9.0' }));
  // Only app/ has a TypeScript, and golem has none of its own, so the version it names is the directory the lookup started from.
  const result = await command(project({}), process.execPath, [binary, 'build', '--config', path.join(root, 'golem.yaml')], { allowFailure: true, env: CHOSEN_ROOT });
  assert.notEqual(result.code, 0);
  assert.match(result.stderr, /golem supports TypeScript 6\.0\+ and 7\.1\+; found 5\.9\.0 at .*app/);
});

test('an exec child gets GOLEM_TYPESCRIPT_ROOT only when the user set it', async () => {
  const root = project({ 'golem.yaml': GENERATOR_ONLY, 'tsconfig.json': '{}' });
  const config = path.join(root, 'golem.yaml');
  const exec = (env: NodeJS.ProcessEnv) => command(root, process.execPath, [binary, 'exec', '--config', config, '--', process.execPath, '-e', 'process.exit(process.env.GOLEM_TYPESCRIPT_ROOT === undefined ? 0 : 1)'], { allowFailure: true, env });
  assert.equal((await exec(CHOSEN_ROOT)).code, 0, 'a root golem chose reached the child');
  assert.equal((await exec({ GOLEM_TYPESCRIPT_ROOT: root })).code, 1, 'the root the user set did not reach the child');
});
