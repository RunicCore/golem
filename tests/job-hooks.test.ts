// A job offers hooks by name and core hands it the participants that extensions add. The test packages are tests/fixtures/extensions/hooked (a job that offers
// the hook `hooked.note`) and tests/fixtures/extensions/probe (extensions `note`, `stray` and `broken`).
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test, { type TestContext } from 'node:test';

import { runPipeline } from '#golem/cli';

import { copyFixture, createFixtureProject, linkGolemPackages, listProjectDependencies } from './fixture-project.js';

const HEADER = '/* Generated by @fixture/hooked. Do not edit. */';

/** An app with the two test packages installed, `in.txt` holding `hello`, and a golem.yaml with the `hooked` block followed by `blocks`. */
function app(t: TestContext, blocks: string): string {
  const root = createFixtureProject(t, 'golem-job-hooks-');
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'job-hooks-app', private: true, type: 'module' }));
  linkGolemPackages(root, ['golem']);
  copyFixture(path.join(root, 'node_modules/@fixture/hooked'), 'extensions/hooked');
  copyFixture(path.join(root, 'node_modules/@fixture/probe'), 'extensions/probe');
  listProjectDependencies(root, ['@fixture/hooked', '@fixture/probe']);
  fs.writeFileSync(path.join(root, 'in.txt'), 'hello\n');
  fs.writeFileSync(path.join(root, 'golem.yaml'), `version: 1\nhooked:\n  output: notes.txt\n  input: in.txt\n  log: runs.log\n${blocks}`);
  return root;
}

const NOTE = 'probe:\n  extensions:\n    note:\n      prefix: "> "\n';
const read = (root: string, name: string): string => fs.readFileSync(path.join(root, name), 'utf8');
const generate = (root: string): Promise<unknown> => runPipeline(path.join(root, 'golem.yaml'));

test('the participant of an enabled extension reaches the job that offers the hook, and a hook that nothing fills is an empty list', async (t) => {
  // protects: T-781 core routes the participants of the extensions that fill a hook to the job that offers it
  const filled = app(t, NOTE);
  await generate(filled);
  assert.equal(read(filled, 'notes.txt'), `${HEADER}\nhello\n> hello\n`);

  const unfilled = app(t, '');
  await generate(unfilled);
  assert.equal(read(unfilled, 'notes.txt'), `${HEADER}\nhello\n`);
});

test('an extension that fills a hook that no job offers stops the run before a job runs, naming the extension, the hook and the hooks offered', async (t) => {
  // protects: T-781 an extension on a hook no job offers is a configuration error
  const root = app(t, 'probe:\n  extensions:\n    stray:\n');
  await assert.rejects(generate(root), /Extension "stray" of @fixture\/probe \(block probe\) fills the hook "nobody\.offers", which no job of this golem\.yaml offers\. Hooks offered: hooked\.note\./);
  assert.equal(fs.existsSync(path.join(root, 'runs.log')), false);
});

test('a participant that throws, or an entry that does not load, stops the run as a fault of its extension package', async (t) => {
  // protects: D-115 a fault in an extension's code stops the run, with the package named
  const throwing = app(t, 'probe:\n  extensions:\n    note:\n      prefix: ">"\n      explode: true\n');
  await assert.rejects(generate(throwing), /Extension "note" of @fixture\/probe \(block probe\) threw while it filled the hook "hooked\.note": note participant exploded\. This is a fault in @fixture\/probe; golem stops here\./);
  assert.equal(fs.existsSync(path.join(throwing, 'notes.txt')), false);

  const broken = app(t, 'probe:\n  extensions:\n    broken:\n');
  await assert.rejects(generate(broken), /Extension "broken" of @fixture\/probe \(block probe\) did not load .*broken entry\. This is a fault in @fixture\/probe/);
});

test('the job runs again when an extension on its hook changes its options or its code, and not otherwise', async (t) => {
  // protects: T-781 the cache key holds the digest of every extension on the job's hooks
  const root = app(t, NOTE);
  const runs = (): number => read(root, 'runs.log').split('\n').filter(Boolean).length;

  await generate(root);
  assert.equal(runs(), 1);
  await generate(root);
  assert.equal(runs(), 1, 'nothing changed');

  fs.writeFileSync(path.join(root, 'golem.yaml'), read(root, 'golem.yaml').replace('prefix: "> "', 'prefix: "# "'));
  await generate(root);
  assert.equal(runs(), 2, 'other options');
  assert.equal(read(root, 'notes.txt'), `${HEADER}\nhello\n# hello\n`);
  await generate(root);
  assert.equal(runs(), 2, 'the new options are recorded');

  const entry = path.join(root, 'node_modules/@fixture/probe/note.mjs');
  fs.writeFileSync(entry, `${fs.readFileSync(entry, 'utf8')}// edited\n`);
  await generate(root);
  assert.equal(runs(), 3, 'other extension code');
});
