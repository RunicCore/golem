test('unrecorded generated-marker leftovers are preserved by generate and reported by check', (t: TestContext) => {
  // protects: E-34 the scan for unrecorded outputs runs only with check; generate neither fails on nor touches a leftover
  const { config, job, filename } = fixture(t);
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  const orphan = path.join(config.directory, 'src/orphan.model.generated.ts');
  fs.writeFileSync(orphan, content(1));
  const before = fs.statSync(orphan, { bigint: true }).mtimeNs;
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], true),
    /drift|Unrecorded generated output/,
  );
  assert.equal(fs.existsSync(filename), false);
  assert.equal(fs.readFileSync(orphan, 'utf8'), content(1));
  assert.equal(fs.statSync(orphan, { bigint: true }).mtimeNs, before);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], false);
  assert.equal(fs.readFileSync(filename, 'utf8'), content(2));
  assert.equal(fs.readFileSync(orphan, 'utf8'), content(1));
});

test('a temporary file that a killed write left is no drift for check, and a write that runs removes it unless its process still runs', (t: TestContext) => {
  // protects: T-872 golem check failed on the temporary file of a write that was killed, and generate never removed it
  const { config } = fixture(t);
  const sdk = path.join(config.directory, 'sdk');
  const job = jobWithFacts('sdks:a', '@acme/sdk', { outputs: [{ path: sdk, kind: 'folder' }] });
  const sdkConfig = { ...config, jobs: [job] };
  const client = { path: path.join(sdk, 'client.ts'), content: '/* Generated by @acme/sdk. */\nexport const a = 1;\n' };
  applyJob(sdkConfig, loadInventory(sdkConfig), job, [client], false);
  // The pid of a process that has exited names a killed write; the pid of this process names a write in flight.
  const deadPid = spawnSync(process.execPath, ['-e', '']).pid;
  const leftover = path.join(sdk, `client.ts.${deadPid}.0123456789ab.tmp`);
  const running = path.join(sdk, `client.ts.${process.pid}.0123456789ab.tmp`);
  const lookalike = path.join(sdk, `client.ts.${deadPid}.not-hex.tmp`);
  const unmarked = path.join(sdk, `client.ts.${deadPid}.ba9876543210.tmp`);
  for (const filename of [leftover, running, lookalike]) fs.writeFileSync(filename, client.content);
  fs.writeFileSync(unmarked, 'partial');
  assert.throws(() => applyJob(sdkConfig, loadInventory(sdkConfig), job, [client], true), new Error(`Unrecorded generated output drift for sdks:a:\n  ${path.relative(process.cwd(), lookalike)}`));
  fs.rmSync(lookalike);
  assert.doesNotThrow(() => applyJob(sdkConfig, loadInventory(sdkConfig), job, [client], true));
  assert.deepEqual(applyJob(sdkConfig, loadInventory(sdkConfig), job, [client], false), { written: [], removed: [] });
  assert.deepEqual(fs.readdirSync(sdk).sort(), ['client.ts', path.basename(running), path.basename(unmarked)].sort());
});

