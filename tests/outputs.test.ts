test('inventory rejects inconsistent owner and job combinations', (t: TestContext) => {
  const { config } = fixture(t);
  fs.mkdirSync(path.dirname(config.inventoryFile), { recursive: true });

  // Inconsistent: owner is openapi but job is models
  fs.writeFileSync(config.inventoryFile, JSON.stringify({
    version: 1,
    files: {
      'src/item.model.generated.ts': {
        owner: '@exprtlabs/golem-openapi',
        job: 'models:.',
        digest: digest(content(1)),
      },
    },
  }));
  assert.throws(() => loadInventory(config), /ownership conflict.*Inventory owner and job disagree/);

  // Inconsistent: owner is golem-model but job is openapi
  fs.writeFileSync(config.inventoryFile, JSON.stringify({
    version: 1,
    files: {
      'sdk/models.ts': {
        owner: '@exprtlabs/golem-model',
        job: 'openapi:sdk',
        digest: digest(content(1)),
      },
    },
  }));
  assert.throws(() => loadInventory(config), /ownership conflict.*Inventory owner and job disagree/);

  // Malformed digest
  fs.writeFileSync(config.inventoryFile, JSON.stringify({
    version: 1,
    files: {
      'src/item.model.generated.ts': {
        owner: '@exprtlabs/golem-model',
        job: 'models:.',
        digest: 'not-a-valid-sha256',
      },
    },
  }));
  assert.throws(() => loadInventory(config), /Invalid generated inventory entry/);
});

test('changing only inventory owner blocks check and applyJob without destructive adoption', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  const artifacts = [{ path: filename, content: content(1) }];
  applyJob(config, loadInventory(config), job, artifacts, false);

  // Mutate inventory owner from @exprtlabs/golem-model to @exprtlabs/golem-openapi with openapi job
  fs.writeFileSync(config.inventoryFile, JSON.stringify({
    version: 1,
    files: {
      'src/item.model.generated.ts': {
        owner: '@exprtlabs/golem-openapi',
        job: 'openapi:other',
        digest: digest(content(1)),
        destination: 'src',
        destinationKind: 'directory',
      },
    },
  }));

  // Both check=true and check=false must detect the ownership conflict with the existing job
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], true),
    /Generated output is owned by another job/,
  );
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], false),
    /Generated output is owned by another job/,
  );

  // Verify the file was not destructively overwritten
  assert.equal(fs.readFileSync(filename, 'utf8'), content(1));
});

test('a handwritten file at an expected output path stops generation and is left unchanged', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  const handwritten = 'export const mine = true;\n';
  fs.writeFileSync(filename, handwritten);
  for (const check of [true, false]) {
    assert.throws(
      () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], check),
      (error: unknown) => error instanceof Error
        && error.message.includes(filename)
        && /not generated by @exprtlabs\/golem-model/.test(error.message),
    );
  }
  assert.equal(fs.readFileSync(filename, 'utf8'), handwritten);
  // A file with the generator's marker but no inventory entry (for example after deleting .golem/) is adopted.
  fs.writeFileSync(filename, content(0));
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], false);
  assert.equal(fs.readFileSync(filename, 'utf8'), content(1));
});

test('a recorded file that a person replaced is kept when its job is retired, and no other file is deleted', (t: TestContext) => {
  // protects: T-44 a hand-written file that replaced a recorded generated file is never deleted
  const { config, job, filename } = fixture(t);
  const generated = path.join(config.directory, 'src/second.model.generated.ts');
  applyJob(config, loadInventory(config), job, [
    { path: generated, content: content(1) },
    { path: filename, content: content(2) },
  ], false);
  const handwritten = 'export const mine = true;\n';
  fs.writeFileSync(filename, handwritten);
  const retired: GolemConfig = { ...config, jobs: [] };
  for (const check of [true, false]) {
    assert.throws(
      () => removeRetiredJobs(retired, loadInventory(retired), check),
      new Error(`Refusing to delete ${filename}: it no longer holds the generated content of @exprtlabs/golem-model. Move it, or delete it yourself.`),
    );
  }
  assert.equal(fs.readFileSync(filename, 'utf8'), handwritten);
  assert.equal(fs.readFileSync(generated, 'utf8'), content(1));
  assert.deepEqual(Object.keys(loadInventory(config).files), ['src/item.model.generated.ts', 'src/second.model.generated.ts']);
});

test('a recorded file that a person replaced is kept when its job stops writing it, and nothing is written', (t: TestContext) => {
  // protects: T-44 a hand-written file that replaced a recorded generated file is never deleted
  const { config, job, filename } = fixture(t);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], false);
  const handwritten = 'export const mine = true;\n';
  fs.writeFileSync(filename, handwritten);
  const next = path.join(config.directory, 'src/next.model.generated.ts');
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: next, content: content(2) }], false),
    new Error(`Refusing to delete ${filename}: it no longer holds the generated content of @exprtlabs/golem-model. Move it, or delete it yourself.`),
  );
  assert.equal(fs.readFileSync(filename, 'utf8'), handwritten);
  assert.equal(fs.existsSync(next), false);
  assert.deepEqual(Object.keys(loadInventory(config).files), ['src/item.model.generated.ts']);
});

test('a file marked by a package that only starts with the owner name is not overwritten', (t: TestContext) => {
  // protects: T-44 a marker matches the full package name, not a package it only prefixes
  const { config, job, filename } = fixture(t);
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  const other = '/* Generated by @exprtlabs/golem-model-extra. Do not edit. */\nexport const value = 9;\n';
  fs.writeFileSync(filename, other);
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], false),
    new Error(`Refusing to overwrite ${filename}: it was not generated by @exprtlabs/golem-model. Remove or rename it, or change the job's output path.`),
  );
  assert.equal(fs.readFileSync(filename, 'utf8'), other);
});

test('a recorded file that still carries its marker is deleted when its job is retired or stops writing it', (t: TestContext) => {
  // protects: T-44 a recorded generated file that still carries its marker is deleted as before
  const { config, job, filename } = fixture(t);
  const second = path.join(config.directory, 'src/second.model.generated.ts');
  applyJob(config, loadInventory(config), job, [
    { path: filename, content: content(1) },
    { path: second, content: content(2) },
  ], false);
  // A person edited the body; the header stays, so golem still owns the file.
  fs.writeFileSync(filename, `${content(1)}// local note\n`);
  applyJob(config, loadInventory(config), job, [{ path: second, content: content(2) }], false);
  assert.equal(fs.existsSync(filename), false);
  fs.writeFileSync(second, `${content(2)}// local note\n`);
  const retired: GolemConfig = { ...config, jobs: [] };
  removeRetiredJobs(retired, loadInventory(retired), false);
  assert.equal(fs.existsSync(second), false);
  assert.deepEqual(Object.keys(loadInventory(config).files), []);
});

// protects: T-44 a header that ends with a line end right after the package name is a marker
