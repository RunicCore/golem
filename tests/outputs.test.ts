import { test, type TestContext } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { loadInventory, applyJob, removeRetiredJobs, digest } from '#golem/outputs';
import type { GolemConfig, GolemJob } from '#golem/config';

interface OutputFixture {
  config: GolemConfig;
  job: GolemJob;
  filename: string;
}

function fixture(t: TestContext): OutputFixture {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'golem-outputs-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const job: GolemJob = {
    id: 'models:.',
    kind: 'models',
    package: '@exprtlabs/golem-model',
    options: {
      root: directory,
      profile: { mobx: false, validation: true },
    },
  };
  const config: GolemConfig = {
    directory,
    configFile: path.join(directory, 'golem.yaml'),
    inventoryFile: path.join(directory, '.golem/outputs.json'),
    tsconfig: path.join(directory, 'tsconfig.json'),
    tsconfigNamed: false,
    profile: { mobx: false, validation: true },
    jobs: [job],
  };
  return { config, job, filename: path.join(directory, 'src/item.model.generated.ts') };
}

const content = (number: number): string =>
  `/* Generated by @exprtlabs/golem-model. Do not edit. */\nexport const value = ${number};\n`;

test('generation and checks preserve content-stable outputs and inventory mtimes', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  const artifacts = [{ path: filename, content: content(1) }];
  applyJob(config, loadInventory(config), job, artifacts, false);
  const before = [filename, config.inventoryFile].map((file) => ({
    file,
    content: fs.readFileSync(file, 'utf8'),
    mtime: fs.statSync(file).mtimeMs,
  }));
  applyJob(config, loadInventory(config), job, artifacts, false);
  applyJob(config, loadInventory(config), job, artifacts, true);
  for (const entry of before) {
    assert.equal(fs.readFileSync(entry.file, 'utf8'), entry.content);
    assert.equal(fs.statSync(entry.file).mtimeMs, entry.mtime);
  }
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], true),
    /stale/,
  );
  assert.equal(fs.readFileSync(filename, 'utf8'), content(1));
});

test('expected regular outputs are replaceable while inventory ownership remains protected', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  const other = path.join(config.directory, 'src/second.model.generated.ts');
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], false);
  fs.writeFileSync(filename, '/* Generated by @exprtlabs/golem-openapi. Do not edit. */\n');
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [
      { path: other, content: content(2) },
      { path: filename, content: content(3) },
    ], true),
    /stale/,
  );
  // `check` is the read-only stale report; generation then replaces the
  // edited expected file and adopts the previously unowned regular output.
  assert.equal(fs.existsSync(other), false);
  applyJob(config, loadInventory(config), job, [
    { path: other, content: content(2) },
    { path: filename, content: content(3) },
  ], false);
  assert.equal(fs.readFileSync(filename, 'utf8'), content(3));
  assert.equal(fs.readFileSync(other, 'utf8'), content(2));
});

test('interrupted writes recover by adopting exactly the newly expected content', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(1) }], false);
  // Simulate replacement succeeding before the inventory update is persisted.
  fs.writeFileSync(filename, content(2));
  assert.throws(() => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], true), /stale/);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], false);
  assert.equal(loadInventory(config).files['src/item.model.generated.ts']?.digest, digest(content(2)));
  const recovered = path.join(config.directory, 'src/new.model.generated.ts');
  fs.writeFileSync(recovered, content(3));
  applyJob(config, loadInventory(config), job, [
    { path: filename, content: content(2) },
    { path: recovered, content: content(3) },
  ], false);
  assert.equal(loadInventory(config).files['src/new.model.generated.ts']?.digest, digest(content(3)));
});

test('legacy markers are never adopted or removed', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  const legacy = '/* Generated by @example/foreign-generator. */\n';
  assert.throws(() => applyJob(config, loadInventory(config), job, [{ path: filename, content: legacy }], false), /ownership marker/);
});

test('unrecorded generated-marker leftovers are preserved by generate and reported by check', (t: TestContext) => {
  const { config, job, filename } = fixture(t);
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  const orphan = path.join(config.directory, 'src/orphan.model.generated.ts');
  fs.writeFileSync(orphan, content(1));
  const before = fs.statSync(orphan, { bigint: true }).mtimeNs;
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], true),
    /drift|Unrecorded generated output/,
  );
  assert.equal(fs.existsSync(filename), false);
  assert.equal(fs.readFileSync(orphan, 'utf8'), content(1));
  assert.equal(fs.statSync(orphan, { bigint: true }).mtimeNs, before);
  applyJob(config, loadInventory(config), job, [{ path: filename, content: content(2) }], false);
  assert.equal(fs.readFileSync(filename, 'utf8'), content(2));
  assert.equal(fs.readFileSync(orphan, 'utf8'), content(1));
});

test('generate does not list the output tree for leftovers; only check does', (t: TestContext) => {
  // protects: E-34 the scan for unrecorded outputs runs only with check
  const { config, job, filename } = fixture(t);
  const artifacts = [{ path: filename, content: content(1) }];
  const listing = t.mock.method(fs, 'readdirSync');
  const listed = (): unknown[] => listing.mock.calls.map(call => call.arguments[0]).filter(directory => String(directory).startsWith(config.directory));
  applyJob(config, loadInventory(config), job, artifacts, false);
  applyJob(config, loadInventory(config), job, artifacts, false);
  assert.deepEqual(listed(), []);
  applyJob(config, loadInventory(config), job, artifacts, true);
  assert.deepEqual(listed(), [path.join(config.directory, 'src/generated/models'), path.join(config.directory, 'src')], 'check lists the output folder and the source folder of the models job');
});

