// protects: T-770 the codec key table is core's own record, not a job output
test('the codec key table is written and removed by core for the boundary provider, outside the inventory and the markers', (t: TestContext) => {
  const { config, filename } = fixture(t);
  const provider = jobWithFacts('models:.', '@exprtlabs/golem-model', { ownedRoots: [config.directory], provides: [MODEL_BOUNDARY] });
  const providerConfig = configFor(config.directory, provider);
  const keys = codecKeysPath(config.directory);
  const table = (name: string): string => `{"version":1,"keys":{"a.model.ts#${name}":"id"}}\n`;
  const companion = { path: filename, content: content(1) };
  applyJob(providerConfig, loadInventory(providerConfig), provider, [companion, { path: keys, content: table('T') }]);
  assert.equal(fs.readFileSync(keys, 'utf8'), table('T'));
  assert.deepEqual(Object.keys(loadInventory(providerConfig).files), ['src/item.model.generated.ts']);
  assert.throws(
    () => applyJob(providerConfig, loadInventory(providerConfig), provider, [companion, { path: keys, content: table('U') }], true),
    new Error(`Generated outputs are stale for models:.:\n  ${path.relative(process.cwd(), keys)}`),
  );
  const docs = jobWithFacts('docs:x', '@acme/docs', { outputs: [{ path: path.join(config.directory, 'sdk'), kind: 'folder' }] });
  assert.throws(
    () => applyJob({ ...providerConfig, jobs: [provider, docs] }, loadInventory(providerConfig), docs, [{ path: keys, content: table('T') }]),
    /escapes the docs:x destination/,
  );
  applyJob(providerConfig, loadInventory(providerConfig), provider, [companion]);
  assert.equal(fs.existsSync(keys), false);
});

