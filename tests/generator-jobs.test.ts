import { test, type TestContext } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { providersFor, runPipeline } from '#golem/cli';
import { loadConfig } from './support/load-config.js';
import { createFixtureProject, linkProjectPackages } from './fixture-project.js';
import { command, golem, workspace } from './support/process.js';

const VERSION = (JSON.parse(fs.readFileSync(path.join(workspace, 'packages/golem/package.json'), 'utf8')) as { version: string }).version;
// outputs.ts `marker()` recognizes a generator's files by this header.
const MARKER = '/* Generated by @fixture/gen. Do not edit. */\n';
const ITEM = `${MARKER}export const label = 'x';\n`;
const CONFIG = ['version: 1', 'acme:', '  output: src/gen', '  options: { label: x }', ''].join('\n');

/** The plan entry of the fixture package: it reads the `acme:` block and declares one job that owns the folder `output`. */
const PLAN_SOURCE = `import path from 'node:path';
export const plan = {
  declare({ directory, block }) {
    const output = path.resolve(directory, block.output);
    return [{
      facts: { id: 'acme', outputs: [{ path: output, kind: 'folder' }], ownedRoots: [], inputFiles: [], inputFolders: [], readsProgram: false, provides: [], needs: [], hooks: [], watch: [] },
      options: { directory, output, options: block.options },
    }];
  },
};
`;

function providerSource(apiVersion: number): string {
  return `import fs from 'node:fs';
import path from 'node:path';
export const apiVersion = ${apiVersion};
export let calls = 0;
export function generate(context) {
  if (fs.existsSync(path.join(context.directory, 'fail-generator'))) throw new Error('fixture generator failed');
  calls += 1;
  fs.writeFileSync(path.join(context.directory, 'calls.txt'), String(calls));
  return { apiVersion: 1, artifacts: [{ path: path.join(context.output, 'item.model.ts'), content: ${JSON.stringify(ITEM)} }], manifestPaths: [], watchInputs: [] };
}
`;
}

/** A project whose package `@fixture/gen` registers the block `acme` (its plan entry, and its generator unless `generator` is false). */
function project(t: TestContext, { apiVersion = 1, version = VERSION, generator = true } = {}): { root: string; config: string } {
  const root = createFixtureProject(t, 'golem-generator-jobs-');
  linkProjectPackages(root, { '@exprtlabs/golem': path.join(workspace, 'packages/golem') });
  fs.writeFileSync(path.join(root, 'package.json'), '{"name":"golem-generator-jobs-fixture","type":"module","dependencies":{"@fixture/gen":"*"}}');
  const provider = path.join(root, 'node_modules/@fixture/gen');
  fs.mkdirSync(provider, { recursive: true });
  const registration = { apiVersion: 2, block: 'acme', plan: './plan', ...(generator ? { generator: './generator' } : {}) };
  fs.writeFileSync(path.join(provider, 'package.json'), JSON.stringify({ name: '@fixture/gen', version, type: 'module', exports: { './plan': './plan.js', './generator': './index.js' }, golem: registration }));
  fs.writeFileSync(path.join(provider, 'plan.js'), PLAN_SOURCE);
  fs.writeFileSync(path.join(provider, 'index.js'), providerSource(apiVersion));
  fs.writeFileSync(path.join(root, 'golem.yaml'), CONFIG);
  return { root, config: path.join(root, 'golem.yaml') };
}

test('a third-party package registers its own block, and the pipeline runs its job from the registered generator', async t => {
  // protects: T-766 the pipeline loads a job's provider from the registry entry of its block
  const { root, config } = project(t);
  await runPipeline(config);
  assert.equal(fs.readFileSync(path.join(root, 'src/gen/item.model.ts'), 'utf8'), ITEM);
});

test('a block whose package declares no generator entry names the package and the block', async t => {
  // protects: T-766 a registered block without a generator entry stops with a message that names both
  const { config } = project(t, { generator: false });
  await assert.rejects(runPipeline(config), /@fixture\/gen registers the golem block "acme" but declares no golem\.generator entry/);
});

test('a generator reporting another API version is rejected', async t => {
  const { config } = project(t, { apiVersion: 99 });
  await assert.rejects(providersFor(loadConfig(config)), /Incompatible generator @fixture\/gen: CLI supports API 1; installed provider reports 99/);
});

test('a third-party generator is not held to the version of golem', async t => {
  for (const version of ['0.1.0', '99.0.0']) {
    const { root, config } = project(t, { version });
    await runPipeline(config);
    assert.equal(fs.readFileSync(path.join(root, 'src/gen/item.model.ts'), 'utf8'), ITEM);
  }
});

test('a failing generator names its package and leaves earlier outputs and the inventory intact', async t => {
  const { root, config } = project(t);
  await runPipeline(config);
  const files = ['src/gen/item.model.ts', '.golem/outputs.json'];
  const before = files.map(file => fs.readFileSync(path.join(root, file), 'utf8'));
  fs.writeFileSync(path.join(root, 'fail-generator'), '');
  await assert.rejects(runPipeline(config), /@fixture\/gen/);
  assert.deepEqual(files.map(file => fs.readFileSync(path.join(root, file), 'utf8')), before);
});

// ---------------------------------------------------------------------------
// The job cache follows the generator's code, not its version
// ---------------------------------------------------------------------------

/** A generator that announces one input, counts its runs in `runs.log` and stamps its output with `emitter`. */
function cachedProviderSource(emitter: string): string {
  return `import fs from 'node:fs';
import path from 'node:path';
export const apiVersion = 1;
export function generate(context) {
  fs.appendFileSync(path.join(context.directory, 'runs.log'), 'run\\n');
  const input = path.join(context.directory, 'generator-input.txt');
  context.onInput(input);
  return { apiVersion: 1, artifacts: [{ path: path.join(context.output, 'item.model.ts'), content: ${JSON.stringify(`${ITEM}// emitter ${emitter}\n`)} }], manifestPaths: [], watchInputs: [input] };
}
`;
}

/** A project whose generator is cachedProviderSource('one'), with `generate` and `check` as the golem CLI runs them. */
function cachedProject(t: TestContext): { root: string; rewriteGenerator: (emitter: string) => void; generate: () => Promise<void>; check: () => Promise<{ code: number | null; stderr: string }>; runs: () => number } {
  const { root } = project(t);
  const providerFile = path.join(root, 'node_modules/@fixture/gen/index.js');
  fs.writeFileSync(providerFile, cachedProviderSource('one'));
  fs.writeFileSync(path.join(root, 'generator-input.txt'), 'input');
  return {
    root,
    rewriteGenerator: emitter => fs.writeFileSync(providerFile, cachedProviderSource(emitter)),
    generate: async () => { await command(root, process.execPath, [golem, 'generate']); },
    check: () => command(root, process.execPath, [golem, 'check'], { allowFailure: true }),
    runs: () => fs.readFileSync(path.join(root, 'runs.log'), 'utf8').split('\n').filter(Boolean).length,
  };
}

const EMITTED = 'src/gen/item.model.ts';

test('a generator whose code changed under the same package version runs again and writes the new output', async t => {
  const { root, rewriteGenerator, generate, runs } = cachedProject(t);
  await generate();
  assert.match(fs.readFileSync(path.join(root, EMITTED), 'utf8'), /\/\/ emitter one\n$/);
  rewriteGenerator('two');
  await generate();
  assert.equal(runs(), 2);
  assert.match(fs.readFileSync(path.join(root, EMITTED), 'utf8'), /\/\/ emitter two\n$/);
});

test('check reports the output of a generator whose code changed under the same package version as out of date', async t => {
  const { root, rewriteGenerator, generate, check } = cachedProject(t);
  await generate();
  rewriteGenerator('two');
  const result = await check();
  assert.notEqual(result.code, 0);
  assert.match(result.stderr, /Generated outputs are stale[^\n]*:\n\s+src\/gen\/item\.model\.ts/);
  assert.match(fs.readFileSync(path.join(root, EMITTED), 'utf8'), /\/\/ emitter one\n$/);
});

const NO_RECORD = /No generation record \(\.golem\/outputs\.json does not exist\)\. Run golem generate or golem build first\./;

test('check on a project that never generated names the missing generation record and writes nothing', async t => {
  // protects: T-32 check names the missing generation record, not a list of stale files
  const { root, check } = cachedProject(t);
  const result = await check();
  assert.equal(result.code, 1);
  assert.match(result.stderr, NO_RECORD);
  assert.doesNotMatch(result.stderr, /stale/);
  assert.equal(fs.existsSync(path.join(root, '.golem')), false);
  assert.equal(fs.existsSync(path.join(root, EMITTED)), false);
});

test('check after generate and a deleted .golem folder names the missing generation record and writes nothing', async t => {
  // protects: T-32 a deleted .golem folder gives the same message as a project that never generated
  const { root, generate, check } = cachedProject(t);
  await generate();
  const generated = fs.readFileSync(path.join(root, EMITTED), 'utf8');
  fs.rmSync(path.join(root, '.golem'), { recursive: true });
  const result = await check();
  assert.equal(result.code, 1);
  assert.match(result.stderr, NO_RECORD);
  assert.doesNotMatch(result.stderr, /stale|drift/);
  assert.equal(fs.existsSync(path.join(root, '.golem')), false);
  assert.equal(fs.readFileSync(path.join(root, EMITTED), 'utf8'), generated);
});

test('a second generate with the generator code and its inputs unchanged runs no job', async t => {
  const { generate, runs } = cachedProject(t);
  await generate();
  await generate();
  assert.equal(runs(), 1);
});
