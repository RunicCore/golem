import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test, type TestContext } from 'node:test';
import type { GolemJob } from '#golem/config';
import { runPipeline } from '#golem/cli';
import { applyJob, loadInventory } from '#golem/outputs';
import { createFixtureProject, linkProjectPackages } from './fixture-project.js';
import { configFor } from './support/output-config.js';
import { workspace } from './support/process.js';
import { writeFixture } from './support/consumer.js';

function pipelineFixture(t: TestContext): { root: string; config: string; external: string; source: string } {
  const root = createFixtureProject(t, 'golem-output-paths-');
  linkProjectPackages(root, Object.fromEntries(['golem', 'golem-model', 'golem-openapi'].map(name => [`@exprtlabs/${name}`, path.join(workspace, 'packages', name)])));
  fs.writeFileSync(path.join(root, 'package.json'), '{"name":"output-paths-fixture","type":"module"}');
  writeFixture(root, { mobx: false, validation: true }, false);

  const external = path.join(path.dirname(root), `golem-output-paths-external-${path.basename(root)}`);
  const sourceDirectory = path.join(external, 'sources');
  const source = path.join(sourceDirectory, 'cart.model.ts');
  fs.mkdirSync(sourceDirectory, { recursive: true });
  fs.mkdirSync(path.join(external, 'node_modules/@exprtlabs'), { recursive: true });
  fs.symlinkSync(path.join(workspace, 'packages/golem'), path.join(external, 'node_modules/@exprtlabs/golem'), 'dir');
  fs.writeFileSync(source, "import type { IModel } from '@exprtlabs/golem/model';\nexport type TCart = IModel<{ value: string }>;\n");
  // One golem.yaml serves one tsconfig, and the model root holds its sources: the external project owns the tsconfig.
  fs.writeFileSync(path.join(external, 'tsconfig.json'), JSON.stringify({
    compilerOptions: { target: 'ES2022', module: 'NodeNext', moduleResolution: 'NodeNext', strict: true, skipLibCheck: true },
    include: ['sources/**/*.ts'],
  }));
  t.after(() => fs.rmSync(external, { recursive: true, force: true }));

  const config = path.join(root, 'golem.yaml');
  fs.writeFileSync(config, [
    'version: 1',
    'mobx: false',
    'validation: true',
    'tsconfig: ../' + path.basename(external) + '/tsconfig.json',
    'openapi:',
    '  - input: api.json',
    '    output: ../' + path.basename(external) + '/sdk',
    '    name: External',
    'models:',
    '  root: ../' + path.basename(external),
    '  sources:',
    '    - ../' + path.basename(external) + '/sources/cart.model.ts',
    '  output: ../' + path.basename(external) + '/models-output',
    '',
  ].join('\n'));
  return { root, config, external, source };
}

function modelJob(root: string, source: string): GolemJob {
  return {
    id: 'models:.',
    kind: 'models',
    package: '@exprtlabs/golem-model',
    options: {
      root,
      sources: [source],
      output: path.join(root, 'src/generated/models'),
      profile: { mobx: false, validation: true },
    },
  };
}

function modelContent(value: number): string {
  return `/* Generated by @exprtlabs/golem-model. Do not edit. */\nexport const value = ${value};\n`;
}

test('YAML pipeline supports external OpenAPI and model roots, sources, and outputs', async (t: TestContext) => {
  const { root, config, external, source } = pipelineFixture(t);
  await runPipeline(config);

  const sdkClient = path.join(external, 'sdk/client.ts');
  // The job validates, so besides the codec keys (.golem/codec-keys.json, beside
  // the inventory) it writes the validators.
  const modelOutput = path.join(root, '.golem/codec-keys.json');
  const validatorsOutput = path.join(external, 'models-output/models.validators.generated.ts');
  const companion = path.join(path.dirname(source), 'cart.model.generated.ts');
  assert.equal(fs.existsSync(sdkClient), true);
  assert.equal(fs.existsSync(modelOutput), true);
  assert.equal(fs.existsSync(validatorsOutput), true);
  assert.equal(fs.existsSync(companion), true);

  const inventoryFile = path.join(root, '.golem/outputs.json');
  const before = fs.readFileSync(inventoryFile);
  const beforeMtime = fs.statSync(inventoryFile, { bigint: true }).mtimeNs;
  const inventory = JSON.parse(before.toString()) as {
    files: Record<string, { destination?: string }>;
  };
  const relative = (filename: string): string => path.relative(root, filename).replaceAll(path.sep, '/');
  assert.equal(inventory.files[relative(sdkClient)]?.destination, relative(path.join(external, 'sdk')));
  assert.equal(inventory.files[relative(modelOutput)]?.destination, '.golem');
  assert.equal(inventory.files[relative(companion)]?.destination, relative(path.dirname(source)));

  await runPipeline(config, { check: true });
  assert.deepEqual(fs.readFileSync(inventoryFile), before);
  assert.equal(fs.statSync(inventoryFile, { bigint: true }).mtimeNs, beforeMtime);
});

test('an OpenAPI SDK written outside the tsconfig directory is generated with its marker', async (t: TestContext) => {
  // protects: T-182 only the models output must lie inside the tsconfig directory
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'golem-sdk-outside-')));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const project = path.join(root, 'project');
  fs.mkdirSync(path.join(project, 'node_modules/@exprtlabs'), { recursive: true });
  for (const name of ['golem', 'golem-openapi']) {
    fs.symlinkSync(path.join(workspace, 'packages', name), path.join(project, 'node_modules/@exprtlabs', name), 'dir');
  }
  fs.writeFileSync(path.join(project, 'package.json'), '{"name":"sdk-outside-fixture","type":"module"}');
  writeFixture(project, { mobx: false, validation: true }, false);
  fs.writeFileSync(path.join(project, 'golem.yaml'), 'version: 1\nopenapi:\n  - input: api.json\n    output: ../sdk\n    name: Profile\n');
  await runPipeline(path.join(project, 'golem.yaml'));
  assert.match(fs.readFileSync(path.join(root, 'sdk/client.ts'), 'utf8'), /^\/\* Generated by @exprtlabs\/golem-openapi/);
  await runPipeline(path.join(project, 'golem.yaml'), { check: true });
});

test('external model companions canonicalize through a symlink and retire safely after retargeting', (t: TestContext) => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'golem-model-companion-paths-')));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const firstSourceDirectory = path.join(root, 'source-target-one');
  const secondSourceDirectory = path.join(root, 'source-target-two');
  const sourceLink = path.join(root, 'source-link');
  for (const directory of [firstSourceDirectory, secondSourceDirectory]) {
    fs.mkdirSync(directory, { recursive: true });
    fs.writeFileSync(path.join(directory, 'cart.model.ts'), 'export type TCart = unknown;\n');
  }
  fs.symlinkSync(firstSourceDirectory, sourceLink, 'dir');

  const sourceFileLink = path.join(sourceLink, 'cart.model.ts');
  const job = modelJob(root, sourceFileLink);
  const config = configFor(root, job);
  const companion = path.join(sourceLink, 'cart.model.generated.ts');
  applyJob(config, loadInventory(config), job, [{ path: companion, content: modelContent(1) }]);
  const firstCompanion = path.join(firstSourceDirectory, 'cart.model.generated.ts');
  const secondCompanion = path.join(secondSourceDirectory, 'cart.model.generated.ts');
  assert.equal(fs.readFileSync(firstCompanion, 'utf8'), modelContent(1));

  fs.unlinkSync(sourceLink);
  fs.symlinkSync(secondSourceDirectory, sourceLink, 'dir');
  applyJob(config, loadInventory(config), job, [{ path: companion, content: modelContent(2) }]);

  assert.equal(fs.existsSync(firstCompanion), false);
  assert.equal(fs.readFileSync(secondCompanion, 'utf8'), modelContent(2));
  const inventory = loadInventory(config);
  assert.equal(inventory.files[path.relative(root, firstCompanion).replaceAll(path.sep, '/')], undefined);
  assert.equal(inventory.files[path.relative(root, secondCompanion).replaceAll(path.sep, '/')].destination, path.relative(root, secondSourceDirectory).replaceAll(path.sep, '/'));
});
