import assert from 'node:assert/strict';
import test from 'node:test';
import { Checker } from 'typescript/unstable/sync';

import { scaleModelSource } from './fixture-templates/models/scale.js';
import { generate } from '#model/generator';
import { createModelProject, writeModelSources } from './model-project.js';
import { compileAndVerifyScaleProject, createScaleProject, SCALE_PROFILE } from './scale-project.js';

test('many model companions share standalone validation and grow with the model count', async t => {
  const sizes: number[] = [];
  for (const count of [10, 100]) {
    const { root } = createScaleProject(t, count);
    // Compiling and executing every companion catches invalid shared bindings
    // that a source-size assertion alone would miss; the 100-model run is in
    // model-generation-scale.acceptance.ts, so here it only generates.
    const artifacts = count === 10 ? await compileAndVerifyScaleProject(root, count) : generate({ root, profile: SCALE_PROFILE }).artifacts;
    assert.equal(artifacts.filter(artifact => artifact.path.endsWith('.model.generated.ts')).length, count);
    assert.equal(artifacts.filter(artifact => artifact.path.endsWith('models.validators.generated.ts')).length, 1);
    sizes.push(artifacts.reduce((sum, artifact) => sum + Buffer.byteLength(artifact.content), 0));
  }
  // A tenfold input increase must stay near linear; no timing threshold depends
  // on the host.
  assert.ok(sizes[1] <= sizes[0] * 11, `generated bytes grew from ${sizes[0]} to ${sizes[1]}`);
});

test('model identity checks grow linearly with the model count', t => {
  // Every field is described once. Resolving structural model identity
  // compares a type against every specification, so it must stay off the
  // primitive and literal paths or the checker traffic grows quadratically.
  const prototype = Checker.prototype as unknown as { isTypeAssignableTo(...args: unknown[]): boolean };
  const original = prototype.isTypeAssignableTo;
  let calls = 0;
  prototype.isTypeAssignableTo = function countedIsTypeAssignableTo(this: Checker, ...args: unknown[]): boolean {
    calls += 1;
    return original.apply(this, args);
  };
  t.after(() => { prototype.isTypeAssignableTo = original; });
  const counts: number[] = [];
  for (const count of [10, 100]) {
    const { root, sourceRoot } = createModelProject(t, {
      prefix: `golem-identity-checks-${count}-`,
      name: null,
      linkWorkspaceNodeModules: true,
    });
    const sources: Record<string, ReturnType<typeof scaleModelSource>> = {};
    for (let index = 0; index < count; index++) sources[`item-${index}.model.ts`] = scaleModelSource({ index });
    writeModelSources(sourceRoot, sources);
    const before = calls;
    const result = generate({ root, profile: { mobx: false, validation: true } });
    assert.equal(result.artifacts.filter(artifact => artifact.path.endsWith('.model.generated.ts')).length, count);
    counts.push(calls - before);
  }
  assert.ok(counts[1] <= counts[0] * 12, `isTypeAssignableTo calls grew from ${counts[0]} to ${counts[1]}`);
});
