import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import { createProgramFromSources } from '#golem/typescript-ts7';

import { generate } from '#model/generator';
import { createModelProject, writeModelSources } from './model-project.js';
import { compileAndVerifyScaleProject, createScaleProject, SCALE_PROFILE, writeScaleModels } from './scale-project.js';

test('many model companions share standalone validation and grow with the model count', async t => {
  const sizes: number[] = [];
  for (const count of [10, 100]) {
    const { root } = createScaleProject(t, count);
    // Compiling and executing every companion catches invalid shared bindings
    // that a source-size assertion alone would miss; the 100-model run is in
    // model-generation-scale.acceptance.ts, so here it only generates.
    const artifacts = count === 10 ? await compileAndVerifyScaleProject(root, count) : generate({ root, profile: SCALE_PROFILE }).artifacts;
    assert.equal(artifacts.filter(artifact => artifact.path.endsWith('.model.generated.ts')).length, count);
    assert.equal(artifacts.filter(artifact => artifact.path.endsWith('models.validators.generated.ts')).length, 1);
    sizes.push(artifacts.reduce((sum, artifact) => sum + Buffer.byteLength(artifact.content), 0));
  }
  // A tenfold input increase must stay near linear; no timing threshold depends
  // on the host.
  assert.ok(sizes[1] <= sizes[0] * 11, `generated bytes grew from ${sizes[0]} to ${sizes[1]}`);
});

test('model identity checks grow linearly with the model count', t => {
  // Every field is described once. Resolving structural model identity
  // compares a type against every specification, so it must stay off the
  // primitive and literal paths or the checker traffic grows quadratically.
  // golem's checker is the seam every identity check goes through. TypeScript 7.1 stores its own checker methods on each
  // checker at first use, so the compiler's prototype is no place to count them.
  const probe = createModelProject(t, { prefix: 'golem-identity-checks-probe-', name: null, linkWorkspaceNodeModules: true });
  const probeSource = path.join(probe.sourceRoot, 'probe.ts');
  fs.writeFileSync(probeSource, 'export const probe = 1;\n');
  const probeProgram = createProgramFromSources({ root: probe.root, sources: [probeSource] });
  const prototype = Object.getPrototypeOf(probeProgram.getTypeChecker()) as { isTypeAssignableTo(...args: unknown[]): boolean };
  probeProgram.close();
  const original = prototype.isTypeAssignableTo;
  let calls = 0;
  prototype.isTypeAssignableTo = function countedIsTypeAssignableTo(this: unknown, ...args: unknown[]): boolean {
    calls += 1;
    return original.apply(this, args);
  };
  t.after(() => { prototype.isTypeAssignableTo = original; });
  const counts: number[] = [];
  for (const count of [10, 100]) {
    const { root, sourceRoot } = createModelProject(t, {
      prefix: `golem-identity-checks-${count}-`,
      name: null,
      linkWorkspaceNodeModules: true,
    });
    writeScaleModels(sourceRoot, count);
    const before = calls;
    const result = generate({ root, profile: { validation: true } });
    assert.equal(result.artifacts.filter(artifact => artifact.path.endsWith('.model.generated.ts')).length, count);
    counts.push(calls - before);
  }
  assert.ok(counts[1] <= counts[0] * 12, `isTypeAssignableTo calls grew from ${counts[0]} to ${counts[1]}`);
});

test('a model that nests a generic thirty levels deep generates', t => {
  // protects: T-447 emitting the conversion of a nested field twice per level made generation time double with each level of nesting
  // The test runner's ceiling is the check: before the fix, depth 30 ran for hours. A leaf of Date makes every level convert.
  const wrap = (leaf: string): string => `${'Wrap<'.repeat(30)}${leaf}${'>'.repeat(30)}`;
  const { root, sourceRoot } = createModelProject(t, { prefix: 'golem-nesting-depth-', name: 'nesting-depth' });
  writeModelSources(sourceRoot, {
    'deep.model.ts': `import type { IModel } from '@exprtlabs/golem/model';\nexport interface Wrap<T> { inner: T }\n`
      + "export type Chain<N extends unknown[]> = N['length'] extends 30 ? { end: true } : { next: Chain<[...N, 1]> };\n"
      + `export type TDeep = IModel<{ plain: ${wrap('string')}; dates: ${wrap('Date')}; chain: Chain<[]> }>;\n`,
  });
  const result = generate({ root, sources: [path.join(sourceRoot, 'deep.model.ts')], profile: { validation: false } });
  assert.ok(result.artifacts.some(artifact => artifact.path.endsWith('deep.model.generated.ts')));
});
