function project(t: TestContext) {
  return createModelProject(t, { prefix: 'runic-model-generator-', name: 'model-generator' });
}

function profileCases(): readonly [{ mobx: boolean; validation: boolean }, { mobx: boolean; validation: boolean }][] {
  return [
    [{ mobx: false, validation: false }, { mobx: false, validation: false }],
    [{ mobx: true, validation: false }, { mobx: true, validation: false }],
    [{ mobx: false, validation: true }, { mobx: false, validation: true }],
    [{ mobx: true, validation: true }, { mobx: true, validation: true }],
  ];
}

test('exports API 1 and emits profile-specific model companions without writes', (t: TestContext) => {
  const { root, sourceRoot } = project(t);
  const source = copyFixtureFile(root, 'models/model-generator/api-profiles/src/payment.model.ts', 'src/payment.model.ts');
  assert.equal(apiVersion, 1);
  for (const [profile, expected] of profileCases()) {
    const result = generate({ root, sources: [source], profile });
    assert.deepEqual(result.manifestPaths, []);
    // payment.model.ts has no custom validation/serde bindings, so the shared
    // models.generated.ts module is never emitted for either profile (see
    // "a job without validation or serde bindings writes no shared bindings
    // file" in tests/model-companions.test.ts).
    assert.equal(result.artifacts.length, 2);
    assert.ok(result.artifacts.some(artifact => artifact.path === path.join(sourceRoot, 'payment.model.generated.ts')));
    assert.equal(fs.existsSync(path.join(sourceRoot, 'payment.model.generated.ts')), false);
    const output = result.artifacts.map(artifact => artifact.content).join('\n');
    assert.match(output, /Generated by @exprtlabs\/model-codegen/);
    assert.match(output, /registerGeneratedModel/);
    assert.doesNotMatch(output, /asGenObservable/);
    if (!expected.mobx) {
      assert.doesNotMatch(output, /@exprtlabs\/codegen\/mobx/);
    }

    if (expected.validation) {
      assert.match(output, /@exprtlabs\/codegen\/(?:ajv|serde)/);
      assert.match(output, /function validate\w*\(/);
      assert.match(output, /createObjectCodec/);
      assert.match(output, /generatedModelFieldsBrand/);
    } else {
      assert.doesNotMatch(output, /@exprtlabs\/codegen\/(?:validation|mobx-validation)/);
      assert.match(output, /generatedModelFieldsBrand/);
    }
  }
});

