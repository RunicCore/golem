    /count\.model\.ts#TCount": "([^"]+)"/.exec(artifacts.find(artifact => artifact.path.endsWith('codec-keys.json'))?.content ?? '')?.[1];
  assert.match(codecId(apps[0].result.artifacts) ?? '', /^TCount_[0-9a-f]{8}$/);
