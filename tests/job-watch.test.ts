import assert from 'node:assert/strict';
import test from 'node:test';
import { observedFolders, watchingJobs } from '#golem/job-facts';
import type { JobFacts } from '#golem/job-facts';

function job(id: string, facts: Partial<Omit<JobFacts, 'id'>> = {}): JobFacts {
  return { id, outputs: [], ownedRoots: [], inputFiles: [], inputFolders: [], readsProgram: false, provides: [], needs: [], hooks: [], watch: [], ...facts };
}

const models = job('model', { ownedRoots: ['/app'], outputs: [{ path: '/app/src/generated', kind: 'folder' }], watch: [{ suffixes: ['.model.ts', '.models.ts'] }] });
const controllers = job('docs', { scanRoots: ['/app'], watch: [{ folder: '/app/src', suffixes: ['.controller.ts'] }] });
const names = (jobs: readonly JobFacts[]): string[] => jobs.map(candidate => candidate.id);
const watching = (filename: string, observed: ReadonlyMap<string, readonly string[]> = new Map()): string[] => names(watchingJobs([models, controllers], filename, observed));

test('a new file reruns the jobs whose watch rule has it inside its folder and its name ending with a suffix', () => {
  // protects: T-771 watch reruns the jobs whose watch rules match a changed file
  assert.deepEqual(watching('/app/src/cart/cart.model.ts'), ['model']);
  assert.deepEqual(watching('/app/lib/items.models.ts'), ['model']);
  assert.deepEqual(watching('/app/src/cart/cart.controller.ts'), ['docs']);
  assert.deepEqual(watching('/app/lib/cart.controller.ts'), [], 'outside the folder of the rule');
  assert.deepEqual(watching('/app/src/cart/cart.service.ts'), [], 'no suffix of any rule');
  assert.deepEqual(watching('/other/cart.model.ts'), [], 'outside every folder of the job');
});

test('a file that a job output holds reruns no job by its name', () => {
  // protects: T-771 a generated file never reruns a job by a watch rule
  assert.deepEqual(watching('/app/src/generated/cart.model.ts'), []);
});

test('a new file beside a file the job read outside its folders reruns the job', () => {
  // protects: T-308 a model added to a shared folder outside the golem.yaml folder is generated by golem watch
  const observed = new Map([['model', ['/shared', '/shared/billing']]]);
  assert.deepEqual(watching('/shared/billing/invoice.model.ts', observed), ['model']);
  assert.deepEqual(watching('/shared/billing/invoice.model.ts'), []);
  assert.deepEqual(watching('/other/invoice.model.ts', observed), []);
  assert.deepEqual(watching('/shared/invoice.controller.ts', observed), [], 'a rule with its own folder ignores the observed folders');
});

test('the folders a job observed are the folders of the files it read', () => {
  const dependencies = new Map([['/shared/money.model.ts', new Set(['model'])], ['/shared/billing/rules.ts', new Set(['model', 'docs'])], ['/app/a.controller.ts', new Set(['docs'])]]);
  assert.deepEqual(observedFolders(dependencies, 'model'), ['/shared', '/shared/billing']);
  assert.deepEqual(observedFolders(dependencies, 'docs'), ['/shared/billing', '/app']);
});
