import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test, type TestContext } from 'node:test';
import type { GolemConfig, GolemJob } from '#golem/config';
import { applyJob, digest, loadInventory, realOutputFiles, removeRetiredJobs } from '#golem/outputs';
import type { OutputFiles } from '#golem/outputs';
import { snapshotFilesystem } from './fixture-project.js';

interface OutputFixture {
  readonly directory: string;
  readonly config: GolemConfig;
  readonly job: GolemJob;
}

function fixture(t: TestContext, inventory = true): OutputFixture {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'golem-recovery-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const profile = { mobx: false, validation: false };
  const job: GolemJob = {
    id: 'models:.',
    kind: 'models',
    package: '@exprtlabs/golem-model',
    options: { root: directory, profile },
  };
  const config: GolemConfig = {
    directory,
    profile,
    configFile: path.join(directory, 'golem.yaml'),
    inventoryFile: path.join(directory, '.golem/outputs.json'),
    tsconfig: path.join(directory, 'tsconfig.json'),
    jobs: [job],
  };
  if (inventory) fs.mkdirSync(path.dirname(config.inventoryFile), { recursive: true });
  return { directory, config, job };
}

function content(value: number): string {
  return `/* Generated by @exprtlabs/golem-model. Do not edit. */\nexport const value = ${value};\n`;
}

function artifact(filename: string, value: number): { path: string; content: string } {
  return { path: filename, content: content(value) };
}

function temporaryEntries(filename: string): string[] {
  const directory = path.dirname(filename);
  if (!fs.existsSync(directory)) return [];
  const prefix = `${path.basename(filename)}.`;
  return fs.readdirSync(directory).filter((entry) => entry.startsWith(prefix) && entry.endsWith('.tmp')).sort();
}

test('check reports edited obsolete artifacts without mutation and generate removes them', (t: TestContext) => {
  const { directory, config, job } = fixture(t);
  const safe = path.join(directory, 'src/safe.model.generated.ts');
  const modified = path.join(directory, 'src/modified.model.generated.ts');
  applyJob(config, loadInventory(config), job, [artifact(safe, 1), artifact(modified, 2)]);
  fs.writeFileSync(modified, `${content(2)}// local edit\n`);
  const userFile = path.join(directory, 'src/notes.ts');
  fs.writeFileSync(userFile, 'handwritten');

  const before = snapshotFilesystem(directory);
  assert.throws(() => applyJob(config, loadInventory(config), job, [], true), /stale/);
  assert.deepEqual(snapshotFilesystem(directory), before);
  applyJob(config, loadInventory(config), job, [], false);
  assert.equal(fs.existsSync(safe), false);
  assert.equal(fs.existsSync(modified), false);
  assert.equal(fs.readFileSync(userFile, 'utf8'), 'handwritten');
});

test('retired-job checks stay read-only and generation removes modified artifacts', (t: TestContext) => {
  const { directory, config, job } = fixture(t);
  const safe = path.join(directory, 'src/safe.model.generated.ts');
  const modified = path.join(directory, 'src/modified.model.generated.ts');
  applyJob(config, loadInventory(config), job, [artifact(safe, 1), artifact(modified, 2)]);
  fs.writeFileSync(modified, `${content(2)}// local edit\n`);
  const retiredConfig: GolemConfig = { ...config, jobs: [] };
  const before = snapshotFilesystem(directory);
  assert.throws(
    () => removeRetiredJobs(retiredConfig, loadInventory(config), true),
    /removed jobs/,
  );
  assert.deepEqual(snapshotFilesystem(directory), before);
  removeRetiredJobs(retiredConfig, loadInventory(config), false);
  assert.equal(fs.existsSync(safe), false);
  assert.equal(fs.existsSync(modified), false);
});

test('a failed second replacement preserves the earlier per-file success and last on-disk inventory', (t: TestContext) => {
  const { directory, config, job } = fixture(t);
  const first = path.join(directory, 'src/first.model.generated.ts');
  const second = path.join(directory, 'src/second.model.generated.ts');
  const before = [artifact(first, 1), artifact(second, 2)];
  const after = [artifact(first, 3), artifact(second, 4)];
  applyJob(config, loadInventory(config), job, before);
  const inventory = fs.readFileSync(config.inventoryFile);
  const inventoryMtime = fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs;
  const failing: OutputFiles = {
    ...realOutputFiles,
    rename: (source, destination) => {
      if (path.resolve(destination) === second) {
        throw Object.assign(new Error('simulated second artifact rename failure'), { code: 'EIO' });
      }
      realOutputFiles.rename(source, destination);
    },
  };
  assert.throws(() => applyJob(config, loadInventory(config), job, after, false, failing), /simulated second artifact rename failure/);

  assert.equal(fs.readFileSync(first, 'utf8'), content(3));
  assert.equal(fs.readFileSync(second, 'utf8'), content(2));
  assert.deepEqual(fs.readFileSync(config.inventoryFile), inventory);
  assert.equal(fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs, inventoryMtime);
  assert.deepEqual(temporaryEntries(first), []);
  assert.deepEqual(temporaryEntries(second), []);
  assert.deepEqual(temporaryEntries(config.inventoryFile), []);

  const beforeCheck = snapshotFilesystem(directory);
  assert.throws(() => applyJob(config, loadInventory(config), job, after, true), /stale/);
  assert.deepEqual(snapshotFilesystem(directory), beforeCheck);

  const firstMtime = fs.statSync(first, { bigint: true }).mtimeNs;
  applyJob(config, loadInventory(config), job, after);
  assert.equal(fs.statSync(first, { bigint: true }).mtimeNs, firstMtime);
  assert.equal(fs.readFileSync(second, 'utf8'), content(4));
  assert.equal(loadInventory(config).files['src/first.model.generated.ts']?.digest, digest(content(3)));
  assert.equal(loadInventory(config).files['src/second.model.generated.ts']?.digest, digest(content(4)));
});

test('a failed cleanup of the temporary file does not hide the rename failure that caused it', (t: TestContext) => {
  // protects: T-490 the unlink in the finally block threw over the first error, so the report named only the cleanup
  const { directory, config, job } = fixture(t);
  const target = path.join(directory, 'src/first.model.generated.ts');
  const renameFailure = Object.assign(new Error('simulated artifact rename failure'), { code: 'EIO' });
  const failing: OutputFiles = {
    ...realOutputFiles,
    rename: () => { throw renameFailure; },
    unlink: () => { throw Object.assign(new Error('simulated unlink refusal'), { code: 'EACCES' }); },
  };
  assert.throws(
    () => applyJob(config, loadInventory(config), job, [artifact(target, 1)], false, failing),
    (error: Error & { code?: string }) => /^simulated artifact rename failure\. Golem could not remove the temporary file .*\.tmp either: simulated unlink refusal$/.test(error.message) && error.cause === renameFailure && error.code === 'EIO',
  );
});

test('a failed stale unlink leaves earlier removal visible and retry tolerates its missing file', (t: TestContext) => {
  const { directory, config, job } = fixture(t);
  const kept = path.join(directory, 'src/kept.model.generated.ts');
  const firstStale = path.join(directory, 'src/first-stale.model.generated.ts');
  const secondStale = path.join(directory, 'src/second-stale.model.generated.ts');
  applyJob(config, loadInventory(config), job, [
    artifact(kept, 1),
    artifact(firstStale, 2),
    artifact(secondStale, 3),
  ]);
  const inventory = fs.readFileSync(config.inventoryFile);
  const inventoryMtime = fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs;
  const failing: OutputFiles = {
    ...realOutputFiles,
    unlink: filename => {
      if (path.resolve(filename) === secondStale) {
        throw Object.assign(new Error('simulated second stale unlink failure'), { code: 'EIO' });
      }
      realOutputFiles.unlink(filename);
    },
  };
  assert.throws(() => applyJob(config, loadInventory(config), job, [artifact(kept, 1)], false, failing), /simulated second stale unlink failure/);

  assert.equal(fs.existsSync(firstStale), false);
  assert.equal(fs.readFileSync(secondStale, 'utf8'), content(3));
  assert.deepEqual(fs.readFileSync(config.inventoryFile), inventory);
  assert.equal(fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs, inventoryMtime);
  assert.deepEqual(temporaryEntries(config.inventoryFile), []);

  applyJob(config, loadInventory(config), job, [artifact(kept, 1)]);
  assert.equal(fs.existsSync(firstStale), false);
  assert.equal(fs.existsSync(secondStale), false);
  assert.deepEqual(Object.keys(loadInventory(config).files), ['src/kept.model.generated.ts']);
});

test('inventory rename failure after output mutations can be retried with replacement content', (t: TestContext) => {
  const { directory, config, job } = fixture(t);
  const existing = path.join(directory, 'src/existing.model.generated.ts');
  const added = path.join(directory, 'src/added.model.generated.ts');
  applyJob(config, loadInventory(config), job, [artifact(existing, 1)]);
  const oldInventory = fs.readFileSync(config.inventoryFile);
  const oldInventoryMtime = fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs;
  const expected = [artifact(existing, 2), artifact(added, 3)];
  const failing: OutputFiles = {
    ...realOutputFiles,
    rename: (source, destination) => {
      if (path.resolve(destination) === config.inventoryFile) {
        throw Object.assign(new Error('simulated inventory rename failure'), { code: 'EIO' });
      }
      realOutputFiles.rename(source, destination);
    },
  };
  assert.throws(() => applyJob(config, loadInventory(config), job, expected, false, failing), /simulated inventory rename failure/);

  assert.equal(fs.readFileSync(existing, 'utf8'), content(2));
  assert.equal(fs.readFileSync(added, 'utf8'), content(3));
  assert.deepEqual(fs.readFileSync(config.inventoryFile), oldInventory);
  assert.equal(fs.statSync(config.inventoryFile, { bigint: true }).mtimeNs, oldInventoryMtime);
  assert.deepEqual(temporaryEntries(existing), []);
  assert.deepEqual(temporaryEntries(added), []);
  assert.deepEqual(temporaryEntries(config.inventoryFile), []);

  const replacement = [artifact(existing, 99), artifact(added, 4)];
  applyJob(config, loadInventory(config), job, replacement);
  assert.equal(fs.readFileSync(existing, 'utf8'), content(99));
  assert.equal(fs.readFileSync(added, 'utf8'), content(4));
  assert.equal(loadInventory(config).files['src/existing.model.generated.ts']?.digest, digest(content(99)));
  assert.equal(loadInventory(config).files['src/added.model.generated.ts']?.digest, digest(content(4)));
});

test('inventory write failure leaves generated content replaceable when inventory is missing', (t: TestContext) => {
  const { directory, config, job } = fixture(t, false);
  const filename = path.join(directory, 'src/item.model.generated.ts');
  const expected = [artifact(filename, 1)];
  const failing: OutputFiles = {
    ...realOutputFiles,
    create: (target, data) => {
      if (target.startsWith(`${config.inventoryFile}.`)) {
        throw Object.assign(new Error('simulated inventory write failure'), { code: 'EIO' });
      }
      realOutputFiles.create(target, data);
    },
  };
  assert.throws(() => applyJob(config, loadInventory(config), job, expected, false, failing), /simulated inventory write failure/);

  assert.equal(fs.readFileSync(filename, 'utf8'), content(1));
  assert.equal(fs.existsSync(config.inventoryFile), false);
  assert.deepEqual(temporaryEntries(filename), []);
  assert.deepEqual(temporaryEntries(config.inventoryFile), []);

  const replacement = [artifact(filename, 2)];
  applyJob(config, loadInventory(config), job, replacement);
  assert.equal(fs.readFileSync(filename, 'utf8'), content(2));
  assert.equal(loadInventory(config).files['src/item.model.generated.ts']?.digest, digest(content(2)));
});
