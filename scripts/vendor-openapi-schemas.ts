import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes the official OpenAPI document schemas as TypeScript modules for
 * @exprtlabs/openapi-to-ts. Ajv 8 resolves `$dynamicRef` incorrectly when the
 * matching `$dynamicAnchor` is not at a schema root, so each
 * `{"$dynamicRef": "#meta"}` becomes `{"$ref": "#/$defs/schema"}`. Without the
 * schema-base extension the dynamic scope holds only `$defs/schema`, so the
 * rewrite does not change what the schema accepts.
 */
const SOURCES = [
  {
    url: 'https://spec.openapis.org/oas/3.1/schema/2026-08-03',
    file: 'oas-3-1.ts',
    exportName: 'OAS_3_1_DOCUMENT_SCHEMA',
  },
  {
    url: 'https://spec.openapis.org/oas/3.2/schema/2026-08-30',
    file: 'oas-3-2.ts',
    exportName: 'OAS_3_2_DOCUMENT_SCHEMA',
  },
] as const;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outputDirectory = path.join(root, 'packages/openapi-to-ts/src/openapi-schemas');

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function replaceDynamicMetaRefs(value: unknown): number {
  if (Array.isArray(value)) return value.reduce<number>((count, item) => count + replaceDynamicMetaRefs(item), 0);
  if (!isObject(value)) return 0;
  let count = 0;
  if (value.$dynamicRef === '#meta') {
    delete value.$dynamicRef;
    value.$ref = '#/$defs/schema';
    count += 1;
  }
  for (const child of Object.values(value)) count += replaceDynamicMetaRefs(child);
  return count;
}

mkdirSync(outputDirectory, { recursive: true });
for (const source of SOURCES) {
  const response = await fetch(source.url, { redirect: 'error' });
  if (!response.ok) throw new Error(`${source.url} returned HTTP ${response.status}`);
  const text = await response.text();
  const sha256 = createHash('sha256').update(text).digest('hex');
  const schema: unknown = JSON.parse(text);
  if (!isObject(schema) || schema.$id !== source.url) throw new Error(`${source.url} has an unexpected $id`);
  const definitions = schema.$defs;
  const schemaDefinition = isObject(definitions) ? definitions.schema : undefined;
  if (!isObject(schemaDefinition) || schemaDefinition.$dynamicAnchor !== 'meta') {
    throw new Error(`${source.url}: $defs/schema.$dynamicAnchor is not "meta"`);
  }
  delete schemaDefinition.$dynamicAnchor;
  const replaced = replaceDynamicMetaRefs(schema);
  if (replaced === 0) throw new Error(`${source.url}: no $dynamicRef "#meta" found`);
  if (JSON.stringify(schema).includes('"$dynamic')) throw new Error(`${source.url}: a $dynamic keyword remains`);
  writeFileSync(path.join(outputDirectory, source.file), [
    '// Generated by scripts/vendor-openapi-schemas.ts; do not edit.',
    `// Source: ${source.url} (sha256 ${sha256}), Apache-2.0, OpenAPI Initiative.`,
    `// ${replaced} \`$dynamicRef: "#meta"\` replaced by \`$ref: "#/$defs/schema"\` for Ajv 8.`,
    "import type { SchemaObject } from 'ajv/dist/2020.js';",
    '',
    `export const ${source.exportName}: SchemaObject = ${JSON.stringify(schema, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`${source.file}: ${replaced} replacements, source sha256 ${sha256}`);
}
