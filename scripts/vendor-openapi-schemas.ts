import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes the official OpenAPI document schemas and the JSON Schema 2020-12
 * meta-schema as TypeScript modules for @exprtlabs/golem-openapi-ts. golem's
 * validator compiler does not support `$dynamicRef` and `$dynamicAnchor`, so
 * every `{"$dynamicRef": "#meta"}` becomes a plain `$ref` to the schema that
 * holds the one `$dynamicAnchor` the references can reach:
 *
 * - OpenAPI document schemas: `{"$ref": "#/$defs/schema"}`. Without the
 *   schema-base extension the dynamic scope holds only `$defs/schema`, so the
 *   rewrite does not change what the schema accepts.
 * - JSON Schema 2020-12 meta-schema: `{"$ref": "https://json-schema.org/draft/2020-12/schema"}`.
 *   Every vocabulary meta-schema declares `$dynamicAnchor: "meta"`, and a
 *   `$dynamicRef: "#meta"` resolves to the outermost one in the dynamic scope.
 *   The meta-schema is only used as the root of a check, so that is always the
 *   dialect schema itself. The `$dynamicAnchor` declarations are then removed.
 */
const SOURCES = [
  {
    url: 'https://spec.openapis.org/oas/3.1/schema/2026-08-03',
    file: 'oas-3-1.ts',
    exportName: 'OAS_3_1_DOCUMENT_SCHEMA',
  },
  {
    url: 'https://spec.openapis.org/oas/3.2/schema/2026-08-30',
    file: 'oas-3-2.ts',
    exportName: 'OAS_3_2_DOCUMENT_SCHEMA',
  },
] as const;

const DIALECT_ID = 'https://json-schema.org/draft/2020-12/schema';
const DIALECT_VOCABULARIES = ['core', 'applicator', 'unevaluated', 'validation', 'meta-data', 'format-annotation', 'content'] as const;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outputDirectory = path.join(root, 'packages/golem-openapi-ts/src/openapi-schemas');

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Schemas that still use `$dynamicRef` or `$dynamicAnchor`; a property of that name inside `properties` has an object value. */
function countDynamicKeywords(value: unknown): number {
  if (Array.isArray(value)) return value.reduce<number>((count, item) => count + countDynamicKeywords(item), 0);
  if (!isObject(value)) return 0;
  let count = 0;
  if (typeof value.$dynamicRef === 'string' || typeof value.$dynamicAnchor === 'string') count += 1;
  for (const child of Object.values(value)) count += countDynamicKeywords(child);
  return count;
}

function replaceDynamicMetaRefs(value: unknown, target: string): number {
  if (Array.isArray(value)) return value.reduce<number>((count, item) => count + replaceDynamicMetaRefs(item, target), 0);
  if (!isObject(value)) return 0;
  let count = 0;
  if (value.$dynamicRef === '#meta') {
    delete value.$dynamicRef;
    value.$ref = target;
    count += 1;
  }
  for (const child of Object.values(value)) count += replaceDynamicMetaRefs(child, target);
  return count;
}

mkdirSync(outputDirectory, { recursive: true });
for (const source of SOURCES) {
  const response = await fetch(source.url, { redirect: 'error' });
  if (!response.ok) throw new Error(`${source.url} returned HTTP ${response.status}`);
  const text = await response.text();
  const sha256 = createHash('sha256').update(text).digest('hex');
  const schema: unknown = JSON.parse(text);
  if (!isObject(schema) || schema.$id !== source.url) throw new Error(`${source.url} has an unexpected $id`);
  const definitions = schema.$defs;
  const schemaDefinition = isObject(definitions) ? definitions.schema : undefined;
  if (!isObject(schemaDefinition) || schemaDefinition.$dynamicAnchor !== 'meta') {
    throw new Error(`${source.url}: $defs/schema.$dynamicAnchor is not "meta"`);
  }
  delete schemaDefinition.$dynamicAnchor;
  const replaced = replaceDynamicMetaRefs(schema, '#/$defs/schema');
  if (replaced === 0) throw new Error(`${source.url}: no $dynamicRef "#meta" found`);
  if (countDynamicKeywords(schema) > 0) throw new Error(`${source.url}: a $dynamic keyword remains`);
  writeFileSync(path.join(outputDirectory, source.file), [
    '// Generated by scripts/vendor-openapi-schemas.ts; do not edit.',
    `// Source: ${source.url} (sha256 ${sha256}), Apache-2.0, OpenAPI Initiative.`,
    `// ${replaced} \`$dynamicRef: "#meta"\` replaced by \`$ref: "#/$defs/schema"\` for golem's validator compiler.`,
    '',
    `export const ${source.exportName}: Readonly<Record<string, unknown>> = ${JSON.stringify(schema, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`${source.file}: ${replaced} replacements, source sha256 ${sha256}`);
}

const dialectIds = [
  DIALECT_ID,
  ...DIALECT_VOCABULARIES.map((name) => `https://json-schema.org/draft/2020-12/meta/${name}`),
];
const dialect: Record<string, unknown> = {};
const dialectHash = createHash('sha256');
let dialectReplaced = 0;
for (const id of dialectIds) {
  const response = await fetch(id, { redirect: 'error' });
  if (!response.ok) throw new Error(`${id} returned HTTP ${response.status}`);
  const text = await response.text();
  dialectHash.update(text);
  const schema: unknown = JSON.parse(text);
  if (!isObject(schema) || schema.$id !== id) throw new Error(`${id} has an unexpected $id`);
  if (schema.$dynamicAnchor !== 'meta') throw new Error(`${id}: $dynamicAnchor is not "meta"`);
  delete schema.$dynamicAnchor;
  dialectReplaced += replaceDynamicMetaRefs(schema, DIALECT_ID);
  if (countDynamicKeywords(schema) > 0) throw new Error(`${id}: a $dynamic keyword remains`);
  dialect[id] = schema;
}
const dialectSha256 = dialectHash.digest('hex');
writeFileSync(path.join(outputDirectory, 'json-schema-2020-12.ts'), [
  '// Generated by scripts/vendor-openapi-schemas.ts; do not edit.',
  `// Source: ${DIALECT_ID} and its meta/ vocabularies (sha256 of the files in order ${dialectSha256}), published by the JSON Schema organization.`,
  `// ${dialectReplaced} \`$dynamicRef: "#meta"\` replaced by \`$ref: "${DIALECT_ID}"\` and every \`$dynamicAnchor\` removed for golem's validator compiler.`,
  '',
  `export const JSON_SCHEMA_2020_12_ID = ${JSON.stringify(DIALECT_ID)};`,
  '',
  '/** The meta-schema and its vocabulary meta-schemas, each under its `$id`. */',
  `export const JSON_SCHEMA_2020_12_META_SCHEMAS: Readonly<Record<string, unknown>> = ${JSON.stringify(dialect, null, 2)};`,
  '',
].join('\n'));
console.log(`json-schema-2020-12.ts: ${dialectReplaced} replacements, source sha256 ${dialectSha256}`);
