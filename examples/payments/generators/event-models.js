import path from 'node:path';

const OWNER = 'payments-example';

/** The API version this generator implements. */
export const apiVersion = 1;

/**
 * Writes one `IModel` declaration per entry of `options.events`.
 * @param {import('@exprtlabs/golem/generator-api').GeneratorJobContext} context
 */
export function generate(context) {
  const events = context.options?.events;
  if (typeof events !== 'object' || events === null || Array.isArray(events)) {
    throw new TypeError('options.events must map event names to their field types.');
  }
  const names = Object.keys(events);
  const declarations = names.map(name => {
    const fields = Object.entries(events[name]).map(([field, type]) => `${field}: ${type}`);
    return [
      `export type T${name} = IModel<{ ${fields.join('; ')} }>;`,
      `export class ${name} extends T${name}BaseModel {}`,
    ].join('\n');
  });
  const content = [
    `/* Generated by ${OWNER}. Do not edit. */`, // Every artifact starts with the package's ownership header.
    "import type { IModel } from '@exprtlabs/golem/model';",
    `import { ${names.map(name => `T${name}BaseModel`).join(', ')} } from './payment-events.model.generated.js';`,
    '',
    declarations.join('\n\n'),
    '',
  ].join('\n');
  return {
    apiVersion: 1,
    artifacts: [{ path: path.join(context.output, 'payment-events.model.ts'), content }],
    manifestPaths: [],
    watchInputs: [],
  };
}
// #endregion event-generator
