function portable(root: string, filename: string): string {
  return path.relative(root, filename).split(path.sep).join('/');
}

// Codec keys

/** Every `<source>#<name>` entry of the program's `iobject-plugin-keys.ts` tables, by the key's last path segment. */
class CodecKeys {
  private readonly byDeclaration = new Map<string, string>();
  private readonly byTail = new Map<string, Set<string>>();
  private readonly names = new Set<string>();

  constructor(program: ts.Program, private readonly root: string) {
    for (const file of program.getSourceFiles()) {
      if (path.basename(file.fileName) !== CODEC_KEY_FILE) continue;
      const openApi = file.text.includes(OPENAPI_KEYS_MARKER);
      const directory = portable(root, path.dirname(file.fileName));
      const visit = (node: ts.Node): void => {
        if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.initializer)
          && (ts.isStringLiteral(node.name) || ts.isIdentifier(node.name))) {
          const name = node.name.text;
          const id = node.initializer.text;
          const hash = name.lastIndexOf('#');
          if (hash > 0 && id !== '') {
            const source = name.slice(0, hash).replace(/\\/g, '/');
            const short = name.slice(hash + 1);
            if (openApi) this.add(`${path.posix.join(directory, source)}#${short}`, id);
            else {
              this.add(`${source}#${short}`, id);
              if (directory !== '' && directory !== '.' && !source.includes('/')) this.add(`${directory}/${source}#${short}`, id);
            }
          }
        }
        ts.forEachChild(node, (child) => { visit(child); return undefined; });
      };
      visit(file);
    }
  }

  private add(declaration: string, id: string): void {
    if (this.byDeclaration.get(declaration) === id) return;
    this.byDeclaration.set(declaration, id);
    this.names.add(declaration.slice(declaration.lastIndexOf('#') + 1));
    const tail = declaration.slice(declaration.lastIndexOf('/') + 1);
    let ids = this.byTail.get(tail);
    if (!ids) this.byTail.set(tail, ids = new Set());
    ids.add(id);
  }

  /** The codec id of the named declaration in the file: an exact path match, else the one id any key with that file name and name holds. */
  idFor(filename: string, name: string): string {
    if (name === '') return '';
    const relative = portable(this.root, filename);
    const exact = this.byDeclaration.get(`${relative}#${name}`);
    if (exact !== undefined) return exact;
    const ids = this.byTail.get(`${path.posix.basename(relative)}#${name}`);
    return ids?.size === 1 ? [...ids][0] : '';
  }

  /** Some key names a declaration called `name`, whether or not one id binds to it. */
  known(name: string): boolean {
    return this.names.has(name);
  }

  idForSymbol(symbol: ts.Symbol): string {
    for (const declaration of symbol.declarations ?? []) {
      const id = this.idFor(declaration.getSourceFile().fileName, symbol.name);
      if (id !== '') return id;
    }
    return '';
  }
}

// Symbols and declarations

function symbolAt(checker: ts.TypeChecker, node: ts.Node): ts.Symbol | undefined {
  const direct = checker.getSymbolAtLocation(node);
  if (direct) return direct;
  if (ts.isQualifiedName(node)) return checker.getSymbolAtLocation(node.right);
  if (ts.isPropertyAccessExpression(node)) return checker.getSymbolAtLocation(node.name);
  return undefined;
}

function resolvedSymbolAt(checker: ts.TypeChecker, node: ts.Node): ts.Symbol | undefined {
  return resolveSymbol(checker, symbolAt(checker, node));
}

function unwrapParentheses(node: ts.Expression): ts.Expression {
  while (ts.isParenthesizedExpression(node)) node = node.expression;
  return node;
}

function declaredInGolem(symbol: ts.Symbol, basenames: readonly string[]): boolean {
  return (symbol.declarations ?? []).some((declaration) => {
    const filename = declaration.getSourceFile().fileName.replace(/\\/g, '/');
    return basenames.includes(path.posix.basename(filename))
      && (filename.includes('@exprtlabs/golem/') || filename.includes('/packages/golem/'));
  });
}

/** The runtime method a call to this callee rewrites to, when the callee is golem's own serde (or validation) function. */
function serdeMethod(checker: ts.TypeChecker, callee: ts.Expression): { readonly name: string; readonly method: string } | undefined {
  const symbol = resolvedSymbolAt(checker, unwrapParentheses(callee));
  const method = symbol && SERDE_METHODS.get(symbol.name);
  if (!symbol || method === undefined) return undefined;
  const owners = symbol.name === 'validate' ? ['validation.ts', 'validation.d.ts'] : ['serde.ts', 'serde.d.ts'];
  return declaredInGolem(symbol, owners) ? { name: symbol.name, method } : undefined;
}

/** The name a serde type argument stands for: a type reference without type arguments or `typeof X`. */
function serdeTypeName(typeNode: ts.TypeNode): ts.EntityName | undefined {
  let node = typeNode;
  while (ts.isParenthesizedTypeNode(node)) node = node.type;
  if (ts.isTypeReferenceNode(node)) return node.typeArguments?.length ? undefined : node.typeName;
  if (ts.isTypeQueryNode(node)) return node.typeArguments?.length ? undefined : node.exprName;
  return undefined;
}

/** `class X extends YBaseModel` with `YBaseModel` a class declared in a generated model module; `Mixin(YBaseModel)` never qualifies. */
function extendsGeneratedBase(checker: ts.TypeChecker, declaration: ts.ClassDeclaration): boolean {
  return (declaration.heritageClauses ?? [])
    .filter((clause) => clause.token === ts.SyntaxKind.ExtendsKeyword)
    .flatMap((clause) => clause.types)
    .some((base) => {
      const expression = unwrapParentheses(base.expression);
      if (!ts.isIdentifier(expression) && !ts.isPropertyAccessExpression(expression)) return false;
      const symbol = resolvedSymbolAt(checker, expression);
      return symbol !== undefined
        && (symbol.flags & ts.SymbolFlags.Class) !== 0
        && symbol.name.endsWith(BASE_MODEL_SUFFIX)
        && (symbol.declarations ?? []).some((candidate) => ts.isClassDeclaration(candidate)
          && GENERATED_MODEL_MODULE.test(candidate.getSourceFile().fileName));
    });
}

/** Offset of the `(` that opens a call's arguments; the argument list starts right after it. */
function openParenthesis(text: string, callArguments: ts.NodeArray<ts.Expression>): number {
  let position = Math.min(callArguments.pos, text.length);
  while (position > 0) {
    const previous = text.charAt(position - 1);
    if (/\s/.test(previous)) { position -= 1; continue; }
    if (text.slice(0, position).endsWith('*/')) {
      const start = text.lastIndexOf('/*', position - 2);
      if (start >= 0) { position = start; continue; }
    }
    return previous === '(' ? position - 1 : -1;
  }
  return -1;
}

function insertion(at: number, text: string): RewriteEdit {
  return { start: at, end: at, expect: '', text };
}

function locate(root: string, file: ts.SourceFile, node: ts.Node, code: string, message: string): GolemDiagnostic {
  const { line, character } = file.getLineAndCharacterOfPosition(node.getStart(file));
  return { code, severity: GolemDiagnosticSeverity.Error, message, file: portable(root, file.fileName), line: line + 1, column: character + 1 };
}

// NestJS codec metadata

/** Whether the name is `name` or a qualified spelling of it, such as `globalThis.Array`. */
function isNamed(typeName: ts.EntityName, ...names: readonly string[]): boolean {
  return names.includes(ts.isIdentifier(typeName) ? typeName.text : typeName.right.text);
}

/** The element type of `T[]`, `Array<T>` and `ReadonlyArray<T>`, through parentheses; any other type as it is. */
function nestModelTypeNode(typeNode: ts.TypeNode): ts.TypeNode {
  let node = typeNode;
  for (;;) {
    if (ts.isParenthesizedTypeNode(node)) node = node.type;
    else if (ts.isArrayTypeNode(node)) node = node.elementType;
    else if (ts.isTypeReferenceNode(node) && node.typeArguments?.length === 1 && isNamed(node.typeName, 'Array', 'ReadonlyArray')) node = node.typeArguments[0];
    else return node;
  }
}

/** The model a method returns, through `Promise<T>`, `T[]`, `readonly T[]`, `Array<T>`; none for a union. */
function nestReturnModel(typeNode: ts.TypeNode): { readonly model: ts.TypeNode; readonly array: boolean } | undefined {
  let node = typeNode;
  let array = false;
  for (;;) {
    if (ts.isParenthesizedTypeNode(node)) node = node.type;
    else if (ts.isArrayTypeNode(node)) { array = true; node = node.elementType; }
    else if (ts.isTypeOperatorNode(node)) {
      if (node.operator !== ts.SyntaxKind.ReadonlyKeyword) return undefined;
      node = node.type;
    } else if (ts.isUnionTypeNode(node)) return undefined;
    else if (ts.isTypeReferenceNode(node) && node.typeArguments?.length === 1 && isNamed(node.typeName, 'Promise')) node = node.typeArguments[0];
    else if (ts.isTypeReferenceNode(node) && node.typeArguments?.length === 1 && isNamed(node.typeName, 'Array', 'ReadonlyArray')) {
      array = true;
      node = node.typeArguments[0];
    } else return { model: node, array };
  }
}

/** The name a decorator is called by, as `@Name()`, `@Name` or `@namespace.Name()`; the receiver is not checked. */
function decoratorName(decorator: ts.Decorator): string | undefined {
  const expression = ts.isCallExpression(decorator.expression) ? decorator.expression.expression : decorator.expression;
  if (ts.isIdentifier(expression)) return expression.text;
  if (ts.isPropertyAccessExpression(expression)) return expression.name.text;
  return undefined;
}

function decoratorNames(node: ts.Node): readonly string[] {
  return (ts.getDecorators(node) ?? []).flatMap((decorator) => decoratorName(decorator) ?? []);
}

/** Whether the node carries the decorator, written plainly or as the aliased import an earlier rewrite added. */
function hasDecorator(names: readonly string[], name: string): boolean {
  return names.includes(name) || names.includes(`${REWRITE_IMPORT_PREFIX}${name}`);
}

interface NestBinding {
  readonly id: string;
  readonly primitive: boolean;
  /** The codec tables name a model with this name, so a type that binds to no id is an error rather than a plain class. */
  readonly known: boolean;
  /** The model type as written, array wrappers removed. */
  readonly label: string;
}

function nestBinding(
  input: { readonly checker: ts.TypeChecker; readonly keys: CodecKeys; readonly file: ts.SourceFile },
  typeNode: ts.TypeNode,
): NestBinding {
  const { checker, keys, file } = input;
  const model = nestModelTypeNode(typeNode);
  const label = model.getText(file);
  const unbound = { id: '', primitive: false, known: false, label };
  if (NEST_PRIMITIVE_TYPES.has(label.slice(label.lastIndexOf('.') + 1))) return { ...unbound, primitive: true };
  const name = serdeTypeName(model);
  const symbol = name && resolvedSymbolAt(checker, name);
  if (!symbol) return unbound;
  const id = keys.idForSymbol(symbol);
  return { ...unbound, id, known: id !== '' || keys.known(symbol.name) };
}

// One file

interface FileScan {
  readonly edits: RewriteEdit[];
  /** Imported name to its module; one module per name, because the applier imports each name once. */
  readonly imports: Map<string, string>;
  readonly diagnostics: GolemDiagnostic[];
  readonly nestSites: NestCodecSite[];
}

function importOf(
  scan: FileScan,
  root: string,
  file: ts.SourceFile,
  node: ts.Node,
  name: string,
  from: string,
): void {
  const existing = scan.imports.get(name);
  if (existing !== undefined && existing !== from) {
    scan.diagnostics.push(locate(root, file, node, CODE_IMPORT_CLASH,
      `"${name}" is imported from both ${existing} and ${from}; golem needs one module for each name it imports for a rewrite.`));
    return;
  }
  scan.imports.set(name, from);
}

/** The module and exported name of a type-only import that binds the name; undefined for any other binding. */
function typeOnlyImportOf(declaration: ts.Node): { readonly from: string; readonly exported: string } | undefined {
  const clauseTypeOnly = (clause: ts.ImportClause): boolean =>
    clause.isTypeOnly === true || clause.phaseModifier === ts.SyntaxKind.TypeKeyword;
  if (ts.isImportSpecifier(declaration)) {
    const clause = declaration.parent.parent;
    const statement = clause.parent;
    if (!ts.isImportClause(clause) || !ts.isImportDeclaration(statement) || !ts.isStringLiteralLike(statement.moduleSpecifier)) return undefined;
    if (!declaration.isTypeOnly && !clauseTypeOnly(clause)) return undefined;
    return { from: statement.moduleSpecifier.text, exported: (declaration.propertyName ?? declaration.name).text };
  }
  if (ts.isImportClause(declaration) && declaration.name && clauseTypeOnly(declaration)) {
    const statement = declaration.parent;
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteralLike(statement.moduleSpecifier)) return undefined;
    return { from: statement.moduleSpecifier.text, exported: 'default' };
  }
  return undefined;
}

/**
 * The text that names the class a `parse<T>` / `fromWireFormat<T>` call constructs: T as the file spells it, or, when
 * T is a type-only import, an aliased value import the applier adds. Undefined when T is not a class.
 */
function constructTarget(
  scan: FileScan,
  input: { readonly root: string; readonly checker: ts.TypeChecker; readonly file: ts.SourceFile },
  name: ts.EntityName,
): string | undefined {
  const symbol = resolvedSymbolAt(input.checker, name);
  if (!symbol || (symbol.flags & ts.SymbolFlags.Class) === 0) return undefined;
  const local = name.getText(input.file);
  if (/[\r\n]/.test(local)) return undefined;
  if (ts.isIdentifier(name)) {
    const typeOnly = (input.checker.getSymbolAtLocation(name)?.declarations ?? [])
      .map(typeOnlyImportOf).find((found) => found !== undefined);
    if (typeOnly) {
      importOf(scan, input.root, input.file, name, typeOnly.exported, typeOnly.from);
      return `${REWRITE_IMPORT_PREFIX}${typeOnly.exported}`;
    }
  }
  return local;
}

function constructOptionEdits(text: string, file: ts.SourceFile, call: ts.CallExpression, target: string): RewriteEdit[] {
  const [first, second] = call.arguments;
  if (!first) return [];
  if (!second) return [insertion(first.end, `, { construct: ${target} }`)];
  const start = second.getStart(file);
  if (text.slice(start, second.end).includes('construct:')) return [];
  // Boundary insertions keep serde calls nested in the options independent edits.
  return [insertion(start, '{ ...'), insertion(second.end, `, construct: ${target} }`)];
}

function scanFile(
  input: { readonly root: string; readonly checker: ts.TypeChecker; readonly keys: CodecKeys; readonly nest: boolean },
  file: ts.SourceFile,
): FileScan {
  const { root, checker, keys, nest } = input;
  const text = file.text;
  const scan: FileScan = { edits: [], imports: new Map(), diagnostics: [], nestSites: [] };
  const classes: { readonly name: string; readonly id: string; readonly end: number }[] = [];
  let reserved: ts.Identifier | undefined;

  const visitCall = (call: ts.CallExpression): void => {
    if (call.questionDotToken || !call.typeArguments?.length) return;
    const serde = serdeMethod(checker, call.expression);
    if (!serde) return;
    const { method } = serde;
    const typeName = call.typeArguments.length === 1 ? serdeTypeName(call.typeArguments[0]) : undefined;
    if (!typeName) {
      scan.diagnostics.push(locate(root, file, call, CODE_TYPE_ARGUMENT, `${method} type argument must be a single type name or typeof expression`));
      return;
    }
    const symbol = resolvedSymbolAt(checker, typeName);
    const id = symbol ? keys.idForSymbol(symbol) : '';
    if (id === '') {
      scan.diagnostics.push(locate(root, file, call, CODE_NO_CODEC, `${method}<${call.typeArguments[0].getText(file)}> has no unique codec id`));
      return;
    }
    const start = call.expression.getStart(file);
    const open = openParenthesis(text, call.arguments);
    if (open < start) throw new Error(`${portable(root, file.fileName)}: the ${method} call could not be rewritten: no opening parenthesis found.`);
    scan.edits.push({
      start,
      end: open + 1,
      expect: text.slice(start, open + 1),
      text: `${REWRITE_IMPORT_PREFIX}requireObjectCodec(${JSON.stringify(id)}).${method}(`,
    });
    importOf(scan, root, file, call, 'requireObjectCodec', SERDE_MODULE);
    if (method === 'parse' || method === 'fromWireFormat') {
      const target = constructTarget(scan, { root, checker, file }, typeName);
      if (target !== undefined) scan.edits.push(...constructOptionEdits(text, file, call, target));
    }
  };

  /** A `@Body()` or `@Query()` parameter of a model gets `@nestModelCodec(id)` before its name. */
  const visitParameter = (parameter: ts.ParameterDeclaration): void => {
    const names = decoratorNames(parameter);
    const decorator = names.find((name) => NEST_PARAMETER_DECORATORS.includes(name));
    if (!parameter.type || decorator === undefined || hasDecorator(names, NEST_CODEC_DECORATOR)) return;
    const { id, primitive, known, label } = nestBinding({ checker, keys, file }, parameter.type);
    if (primitive) return;
    if (id === '') {
      if (known) scan.diagnostics.push(locate(root, file, parameter.type, CODE_NEST_NO_CODEC, `@${decorator}() type ${label} has no unique codec id`));
      return;
    }
    scan.edits.push(insertion(parameter.name.getStart(file), `@${REWRITE_IMPORT_PREFIX}${NEST_CODEC_DECORATOR}(${JSON.stringify(id)}) `));
    importOf(scan, root, file, parameter, NEST_CODEC_DECORATOR, NEST_MODULE);
    const { line, character } = file.getLineAndCharacterOfPosition(parameter.type.getStart(file));
    scan.nestSites.push({ file: portable(root, file.fileName), line: line + 1, column: character + 1, decorator, label, id });
  };

  /** A class method that returns a model gets `@nestModelReturn(id[, true])` before its other decorators. */
  const visitMethod = (method: ts.MethodDeclaration): void => {
    // A decorator is a syntax error on an object literal method, an abstract method and an overload signature.
    if (!method.type || !method.body || !ts.isClassLike(method.parent)) return;
    const returned = nestReturnModel(method.type);
    if (!returned || hasDecorator(decoratorNames(method), NEST_RETURN_DECORATOR)) return;
    const { id, primitive } = nestBinding({ checker, keys, file }, returned.model);
    if (primitive || id === '') return;
    scan.edits.push(insertion(method.getStart(file), `@${REWRITE_IMPORT_PREFIX}${NEST_RETURN_DECORATOR}(${JSON.stringify(id)}${returned.array ? ', true' : ''}) `));
    importOf(scan, root, file, method, NEST_RETURN_DECORATOR, NEST_MODULE);
  };

  const visit = (node: ts.Node): void => {
    if (nest && ts.isParameter(node)) visitParameter(node);
    else if (nest && ts.isMethodDeclaration(node)) visitMethod(node);
    if (ts.isCallExpression(node)) visitCall(node);
    else if (ts.isClassDeclaration(node) && node.name && extendsGeneratedBase(checker, node)) {
      const id = keys.idFor(file.fileName, node.name.text);
      if (id !== '') classes.push({ name: node.name.text, id, end: node.end });
    } else if (ts.isIdentifier(node) && !reserved && node.text.startsWith(REWRITE_IMPORT_PREFIX)) reserved = node;
    ts.forEachChild(node, (child) => { visit(child); return undefined; });
  };
  visit(file);

  // One class registers as its model's class; with several, each registers as <id>#<class> and the model has no default.
  const linked = new Map<string, number>();
  for (const { id } of classes) linked.set(id, (linked.get(id) ?? 0) + 1);
  for (const { name, id, end } of classes) {
    const key = (linked.get(id) ?? 0) > 1 ? `${id}#${name}` : id;
    const statement = `registerIModelClass(${JSON.stringify(key)}, ${name});`;
    // This also matches the aliased statement an earlier rewrite wrote.
    if (text.includes(statement)) continue;
    scan.edits.push(insertion(end, `\n${REWRITE_IMPORT_PREFIX}${statement}`));
    importOf(scan, root, file, file, 'registerIModelClass', SERDE_MODULE);
  }

  // A user binding of the reserved prefix would capture the call the rewrite inserts, so a file that is rewritten may not use one.
  if (reserved && scan.edits.length > 0) {
    scan.diagnostics.push(locate(root, file, reserved, CODE_RESERVED_PREFIX,
      `"${reserved.text}" starts with ${REWRITE_IMPORT_PREFIX}, which golem reserves for the names it adds when it rewrites a file. Rename it.`));
  }
  return scan;
}

// The scan

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function entryFor(text: string, scan: FileScan): RewriteFile {
  const byModule = new Map<string, string[]>();
  for (const [name, from] of scan.imports) byModule.set(from, [...(byModule.get(from) ?? []), name]);
  const imports: RewriteImport[] = [...byModule]
    .sort(([left], [right]) => compareText(left, right))
    .map(([from, names]) => ({ from, names: names.sort(compareText) }));
  const edits = [...scan.edits].sort((left, right) => left.start - right.start || left.end - right.end);
  return { sha256: sha256Hex(text), edits, imports };
}

/** Scan the program's own sources for every rewrite site and return the index and the sites that cannot be rewritten. */
export function scanRewrites(input: ScanInput): ScanResult {
  const { root, program, checker, nest } = input;
  const keys = new CodecKeys(program, root);
  const sources = program.getSourceFiles()
    .filter((file) => !file.isDeclarationFile
      && !program.isSourceFileFromExternalLibrary(file)
      && !program.isSourceFileDefaultLibrary(file)
      && !file.fileName.split(/[\\/]/).includes('node_modules')
      && !isGeneratedCompanion(file.fileName)
      && path.basename(file.fileName) !== CODEC_KEY_FILE)
    .map((file) => ({ file, relative: portable(root, file.fileName) }))
    .sort((left, right) => compareText(left.relative, right.relative));

  const files: Record<string, RewriteFile> = {};
  const diagnostics: GolemDiagnostic[] = [];
  const nestCodecSites: NestCodecSite[] = [];
  for (const { relative, file } of sources) {
    const scan = scanFile({ root, checker, keys, nest }, file);
    if (relative.startsWith('../')) {
      // Index keys are root-relative, so a site here cannot be indexed yet.
      const first = scan.edits.length > 0 ? file.getLineAndCharacterOfPosition(Math.min(...scan.edits.map((edit) => edit.start))) : undefined;
      const site = first ? { line: first.line + 1, column: first.character + 1 } : scan.diagnostics[0];
      if (site) {
        diagnostics.push({
          code: CODE_OUTSIDE_ROOT,
          severity: GolemDiagnosticSeverity.Error,
          message: `"${relative}" has a rewrite site but lies outside the project root. Move it under the root, or run golem generate for the package that contains it.`,
          file: relative,
          line: site.line,
          column: site.column,
        });
      }
      continue;
    }
    diagnostics.push(...scan.diagnostics);
    nestCodecSites.push(...scan.nestSites);
    if (scan.edits.length > 0) files[relative] = entryFor(file.text, scan);
  }
  return { index: { version: 1, golem: GOLEM_VERSION, files }, diagnostics, nestCodecSites };
}

/**
 * The `@Body()` and `@Query()` parameters whose codec id the controllers job's generated operation codecs do not hold. The id the scan stamps and the id the controllers job writes come
 * from separate analyses, so a mismatch means the decorators and the generated operations disagree. A missing registry
 * disagrees with every site.
 */
export function checkNestCodecs(root: string, scanned: ScanResult): GolemDiagnostic[] {
  let registry: string | undefined;
  try {
    registry = fs.readFileSync(operationCodecRegistryPath(root), 'utf8');
  } catch {
    registry = undefined;
  }
  return scanned.nestCodecSites
    .filter((site) => registry === undefined || !registry.includes(JSON.stringify(site.id)))
    .map((site) => ({
      code: CODE_NEST_REGISTRY,
      severity: GolemDiagnosticSeverity.Error,
      message: `@${site.decorator}() type ${site.label} disagrees with generated operation keys`,
      file: site.file,
      line: site.line,
      column: site.column,
    }));
}

/** Write `<root>/.golem/rewrites.json`; the same index always yields the same bytes. Returns whether the file changed. */
export function writeRewriteIndex(root: string, index: RewriteIndex): boolean {
  return atomicWrite(path.join(root, REWRITE_INDEX_PATH), `${JSON.stringify(index, null, 2)}\n`);
}

/** Open the project's program and scan it. `onInput` observes every file the compiler reads. */
export function scanProjectRewrites(input: {
  readonly root: string;
  readonly nest: boolean;
  /** The session and owner of the job that reads this project, so one compiler serves its generation and this scan. */
  readonly session?: GeneratorSession;
  readonly sessionOwner?: string;
  readonly onInput?: InputObserver;
}): ScanResult {
  const { root, nest, session, sessionOwner, onInput } = input;
  const info = createProjectProgram(root, onInput, sessionOwner === undefined ? undefined : retainedProgramSession(session, sessionOwner, root));
  using program = info.program;
  return scanRewrites({ root, program, checker: program.getTypeChecker(), nest });
}

/**
 * Fail, naming the first differing file, when the index on disk is not what `scanned` holds: a bundler would otherwise
 * build from a stale rewrite. A project without an index passes; `golem generate` creates it.
 */
export function assertRewriteIndexCurrent(root: string, scanned: RewriteIndex): void {
  const index = readRewriteIndex(root);
  if (!index) return;
  const differing = [...new Set([...Object.keys(index.files), ...Object.keys(scanned.files)])]
    .sort(compareText)
    .find((relative) => JSON.stringify(index.files[relative]) !== JSON.stringify(scanned.files[relative]));
  if (differing !== undefined) {
    throw new GolemRewriteStaleError(differing, `${differing} is out of date in ${REWRITE_INDEX_PATH}; run golem generate.`);
  }
}
