package main

import (
	"path/filepath"
	"strings"

	shimast "github.com/microsoft/typescript-go/shim/ast"
	shimchecker "github.com/microsoft/typescript-go/shim/checker"
	"github.com/samchon/ttsc/packages/ttsc/driver"
)

type codecKeys struct {
	byDecl  map[string]string
	byShort map[string][]string
}

func loadCodecKeys(prog *driver.Program, cwd string) codecKeys {
	keys := codecKeys{byDecl: map[string]string{}, byShort: map[string][]string{}}
	if prog == nil {
		return keys
	}
	for _, file := range prog.SourceFiles() {
		if file == nil || filepath.Base(file.FileName()) != "iobject-plugin-keys.ts" {
			continue
		}
		openAPIKeys := strings.Contains(file.Text(), "Generated by @exprtlabs/golem-openapi.")
		dir, relErr := filepath.Rel(cwd, filepath.Dir(file.FileName()))
		if relErr != nil {
			dir = filepath.Dir(file.FileName())
		}
		dir = filepath.ToSlash(dir)
		collectCodecKeyProperties(file.AsNode(), func(source, short, id string) {
			source = filepath.ToSlash(source)
			if openAPIKeys {
				keySource := filepath.ToSlash(filepath.Join(dir, filepath.FromSlash(source)))
				keys.add(keySource+"#"+short, id)
				return
			}
			keys.add(source+"#"+short, id)
			if dir != "" && dir != "." && !strings.Contains(source, "/") {
				keys.add(dir+"/"+source+"#"+short, id)
			}
		})
	}
	return keys
}

func collectCodecKeyProperties(node *shimast.Node, emit func(source, short, id string)) {
	if node == nil {
		return
	}
	if node.Kind == shimast.KindPropertyAssignment {
		nameNode := node.Name()
		prop := node.AsPropertyAssignment()
		// Keys and ids are string literals in the generated key file; skip anything else.
		if nameNode != nil && prop.Initializer != nil && prop.Initializer.Kind == shimast.KindStringLiteral &&
			(nameNode.Kind == shimast.KindStringLiteral || nameNode.Kind == shimast.KindIdentifier) {
			name := nameNode.Text()
			value := prop.Initializer.Text()
			if hash := strings.LastIndex(name, "#"); hash > 0 && value != "" {
				emit(name[:hash], name[hash+1:], value)
			}
		}
	}
	node.ForEachChild(func(child *shimast.Node) bool {
		collectCodecKeyProperties(child, emit)
		return false
	})
}

func (k codecKeys) add(decl, id string) {
	if k.byDecl[decl] == id {
		return
	}
	k.byDecl[decl] = id
	short := decl[strings.LastIndex(decl, "#")+1:]
	for _, existing := range k.byShort[short] {
		if existing == id {
			return
		}
	}
	k.byShort[short] = append(k.byShort[short], id)
}

func (k codecKeys) resolveType(checker *shimchecker.Checker, typeNode *shimast.Node, cwd string) (string, bool) {
	nameNode, ok := serdeTypeName(typeNode)
	if !ok || checker == nil || nameNode == nil {
		return "", false
	}
	symbol := symbolAt(checker, nameNode)
	if symbol == nil {
		return "", true
	}
	return k.idForSymbol(symbol, cwd), true
}

func serdeTypeName(typeNode *shimast.Node) (*shimast.Node, bool) {
	node := typeNode
	for node != nil && node.Kind == shimast.KindParenthesizedType {
		paren := node.AsParenthesizedTypeNode()
		if paren == nil {
			return nil, false
		}
		node = paren.Type
	}
	switch {
	case node != nil && node.Kind == shimast.KindTypeReference:
		ref := node.AsTypeReferenceNode()
		if ref == nil || ref.TypeName == nil || (ref.TypeArguments != nil && len(ref.TypeArguments.Nodes) > 0) {
			return nil, false
		}
		return ref.TypeName, true
	case node != nil && node.Kind == shimast.KindTypeQuery:
		query := node.AsTypeQueryNode()
		if query == nil || query.ExprName == nil || (query.TypeArguments != nil && len(query.TypeArguments.Nodes) > 0) {
			return nil, false
		}
		return query.ExprName, true
	default:
		return nil, false
	}
}

func (k codecKeys) idForSymbol(symbol *shimast.Symbol, cwd string) string {
	if symbol == nil {
		return ""
	}
	short := symbol.Name
	if short == "" {
		return ""
	}
	for _, declaration := range symbol.Declarations {
		if declaration == nil {
			continue
		}
		source := shimast.GetSourceFileOfNode(declaration)
		if source == nil {
			continue
		}
		rel := portableRel(cwd, source.FileName())
		if id, ok := k.byDecl[rel+"#"+short]; ok {
			return id
		}
		base := filepath.ToSlash(filepath.Base(rel))
		var hits []string
		suffix := "/" + base + "#" + short
		for key, id := range k.byDecl {
			if key == base+"#"+short || strings.HasSuffix(key, suffix) {
				hits = append(hits, id)
			}
		}
		if uniq := uniqueStrings(hits); len(uniq) == 1 {
			return uniq[0]
		}
	}
	return ""
}

func (k codecKeys) resolve(ident string, checker *shimchecker.Checker, file *shimast.SourceFile, cwd string) string {
	short := ident
	if short == "" {
		return ""
	}
	for _, decl := range declarationFiles(checker, file, ident) {
		rel := portableRel(cwd, decl)
		if id, ok := k.byDecl[rel+"#"+short]; ok {
			return id
		}
		base := filepath.ToSlash(filepath.Base(rel))
		var hits []string
		suffix := "/" + base + "#" + short
		for key, id := range k.byDecl {
			if key == base+"#"+short || strings.HasSuffix(key, suffix) {
				hits = append(hits, id)
			}
		}
		if uniq := uniqueStrings(hits); len(uniq) == 1 {
			return uniq[0]
		}
	}
	return ""
}

func (k codecKeys) known(ident string) bool {
	return ident != "" && len(k.byShort[ident]) > 0
}

func portableRel(cwd, filename string) string {
	rel, err := filepath.Rel(cwd, filename)
	if err != nil {
		return filepath.ToSlash(filename)
	}
	return filepath.ToSlash(rel)
}

func uniqueStrings(values []string) []string {
	seen := map[string]struct{}{}
	var out []string
	for _, value := range values {
		if value == "" {
			continue
		}
		if _, ok := seen[value]; ok {
			continue
		}
		seen[value] = struct{}{}
		out = append(out, value)
	}
	return out
}

func declarationFiles(checker *shimchecker.Checker, file *shimast.SourceFile, ident string) []string {
	if file == nil {
		return nil
	}
	seen := map[string]struct{}{}
	var out []string
	add := func(filename string) {
		if filename == "" {
			return
		}
		if _, ok := seen[filename]; ok {
			return
		}
		seen[filename] = struct{}{}
		out = append(out, filename)
	}
	if checker == nil {
		add(file.FileName())
		return out
	}
	var walk func(*shimast.Node)
	walk = func(node *shimast.Node) {
		if node == nil {
			return
		}
		if node.Kind != shimast.KindIdentifier {
			node.ForEachChild(func(child *shimast.Node) bool {
				walk(child)
				return false
			})
			return
		}
		if identNode := node.AsIdentifier(); identNode != nil && identNode.Text == ident {
			symbol := checker.GetSymbolAtLocation(node)
			if symbol != nil && symbol.Flags&shimast.SymbolFlagsAlias != 0 {
				if aliased := shimchecker.Checker_getAliasedSymbol(checker, symbol); aliased != nil {
					symbol = aliased
				}
			}
			if symbol != nil {
				for _, declaration := range symbol.Declarations {
					if declaration == nil {
						continue
					}
					if source := shimast.GetSourceFileOfNode(declaration); source != nil {
						add(source.FileName())
					}
				}
			}
		}
		node.ForEachChild(func(child *shimast.Node) bool {
			walk(child)
			return false
		})
	}
	walk(file.AsNode())
	if len(out) == 0 {
		add(file.FileName())
	}
	return out
}
